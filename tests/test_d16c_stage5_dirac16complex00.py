class AgreementHelperTests(unittest.TestCase):

    def test_formula_parsers(self):
        m, S, lam, U0, U1 = sp.symbols("m S lam U0 U1")
        syms = {"m": m, "S": S, "lam": lam, "U0": U0, "U1": U1}
        e = T.parse_plain_formula(" -m S + 7 S U'(S) - 8 U(S) ", syms)
        self.assertEqual(sp.expand(e - (-m * S + 7 * S * U1 - 8 * U0)), 0)
        e = T.parse_plain_formula("(1/2)(m S + 2U - S U')", syms)
        self.assertEqual(sp.expand(e - (m * S + 2 * U0 - S * U1) / 2), 0)
        e = T.parse_plain_formula("(1/2)(m S + 2U + S U')", syms)            # a wrong formula is not equal
        self.assertNotEqual(sp.expand(e - (m * S + 2 * U0 - S * U1) / 2), 0)
        y = sp.Symbol("y", real=True)
        r = T.parse_mathematica_trig("(8*(25 - 9*Cos[8*y] + 12*Sin[8*y]))/5", y)
        self.assertEqual(sp.expand(r - sp.Rational(8, 5) * (25 - 9 * sp.cos(8 * y) + 12 * sp.sin(8 * y))), 0)

    def test_report_serialisation_is_deterministic(self):
        doc = {"schemaVersion": 1, "checks": {"S5_a": True}, "measurements": {"x": T.jsonable({"f": Fraction(1, 3), "_hidden": 1})}}
        self.assertEqual(T.canonical_json_bytes(doc), T.canonical_json_bytes(json.loads(T.canonical_json_bytes(doc))))
        self.assertEqual(doc["measurements"]["x"], {"f": "1/3"})
        lines, failed = T.report_lines({"checks": {"S5_a": True, "S5_b": False}, "measurements": {"m": 1}})
        self.assertEqual(failed, 1)
        self.assertIn("check_S5_b=false", lines)
        self.assertEqual(lines[-2:], ["check_count=2", "failed_check_count=1"])


class CommittedReportTests(unittest.TestCase):

    def test_committed_report_is_complete_true_and_current(self):
        path = T.DEFAULT_OUTPUT
        self.assertTrue(os.path.exists(path), "run scripts/check_dirac16complex00.py to create the report")
        with open(path, "r", encoding="utf-8") as handle:
            rep = json.load(handle)
        self.assertEqual(rep["schemaVersion"], 1)
        self.assertEqual(rep["producer"], T.PRODUCER)
        self.assertTrue(all(rep["checks"].values()), [k for k, v in rep["checks"].items() if not v])
        self.assertGreaterEqual(len(rep["checks"]), 49)
        self.assertIn(T.WOLFRAM_CHECK, rep["checks"])
        self.assertFalse(rep["measurements"]["quick"])
        self.assertEqual(rep["measurements"]["families"], list(T.FAMILIES))
        for rel, digest in rep["sourceSha256"].items():
            self.assertEqual(T.sha256_file(os.path.join(REPO, rel)), digest, rel)
        for rel, digest in rep["inputSha256"].items():
            self.assertEqual(T.sha256_file(os.path.join(REPO, rel)), digest, rel)
        with open(path, "rb") as handle:
            raw = handle.read()
        self.assertNotIn(b"\r\n", raw)
        self.assertEqual(raw, T.canonical_json_bytes(rep))


