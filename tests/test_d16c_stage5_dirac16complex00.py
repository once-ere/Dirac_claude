class ExactToolTests(unittest.TestCase):

    def test_poly_arithmetic_and_derivations(self):
        x, y = T.Poly.var(0), T.Poly.var(1)
        p = x * x * y + x * 3 - 2
        self.assertEqual(p.nterms(), 3)
        d = p.partials()
        self.assertTrue((d[0] - (x * y * 2 + 3)).is_zero())
        self.assertTrue((d[1] - x * x).is_zero())
        # derivation with a chain rule: d/dx of U(S) with S = x y is U'(S) * y
        U0, U1 = T.Poly.var(5), T.Poly.var(6)
        S = x * y
        img = {0: T.Poly.const(1), 5: U1 * S.partials()[0]}
        q = (U0 * x).derivation(lambda v: img.get(v))
        self.assertTrue((q - (U0 + U1 * y * x)).is_zero())
        self.assertTrue((T.poly_rename(p, {0: 1, 1: 0}) - (y * y * x + y * 3 - 2)).is_zero())
        self.assertEqual(p.evaluate({0: Fraction(2), 1: Fraction(1, 2)}), Fraction(6))

    def test_dual_numbers_exact_linearisation(self):
        x = T.Dual(Fraction(3), 1)
        f = x * x / (x + 1)
        self.assertEqual(f.a, Fraction(9, 4))
        self.assertEqual(f.b, Fraction(15, 16))          # d/dx x^2/(1+x) = (x^2 + 2x)/(1+x)^2 at 3
        inv = T._mat_inverse_generic([[T.Dual(Fraction(2), 1), Fraction(1)], [Fraction(0), Fraction(1)]])
        self.assertEqual(inv[0][0].a, Fraction(1, 2))
        self.assertEqual(inv[0][0].b, Fraction(-1, 4))

    def test_lcg_reproduces_exported_scalar_densities(self):
        alg = algebra()

        def S_of(seed):
            data = T.lcg_field_data(seed)
            return sum((data[3][a] * alg.C[a][b] * data[0][b] for a in range(16) for b in range(16)), Fraction(0))
        self.assertEqual(S_of(61100), Fraction(-4303, 672))        # vielbein variation G1 p1 (theory export)
        self.assertEqual(S_of(63100), Fraction(5617, 567))         # homogeneous G3 t1 (theory export)
        S0 = S_of(62110)
        self.assertEqual(-Fraction(3, 7) * S0 + 3 * Fraction(5, 11) * S0 * S0, Fraction(923549, 26880))


