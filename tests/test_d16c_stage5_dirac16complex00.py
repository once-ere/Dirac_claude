class LagrangianTests(unittest.TestCase):

    def test_flat_symbolic_euler_lagrange_and_negative_control(self):
        flat = geos().flat()
        ok, d, sl = T.el_symbolic_point(flat, "quartic")
        self.assertTrue(ok, d)
        E = sl.euler_lagrange("chi")
        t_chi, _ = sl.targets()
        wrong = t_chi + T.np.einsum("ij,j->i", flat.gd.C, sl.psi) * sl.V.v("m") * 2    # m -> -m in the target
        self.assertFalse(T.polys_equal(E, wrong, flat.dom))
        ok_u, du, _ = T.el_symbolic_point(flat, "general")
        self.assertTrue(ok_u, du)

    def test_reality_real_restriction_and_relation_flat(self):
        flat = geos().flat()
        ok, d = T.reality_point(flat, random.Random(3))
        self.assertTrue(ok, d)
        ok, d = T.real_restriction_point(flat, False)
        self.assertTrue(ok, d)
        ok, d = T.relation_to_L1(flat)
        self.assertTrue(ok, d)

    def test_grassmann_statements(self):
        gd = geos().gd_qq
        ok, d = T.grassmann_flat_checks(gd, QQ(3, 7), QQ(5, 11))
        self.assertTrue(ok, d)
        ok, d = T.grassmann_mass_term(gd, 17)
        self.assertTrue(ok, d)
        self.assertEqual(d["powerMonomialCounts"][:3], [16, 120, 560])
        self.assertTrue(d["S17Zero"] and d["S16Nonzero"])
        ok, d = T.grassmann_real_flat(gd)
        self.assertTrue(ok, d)
        ok, d = T.grassmann_complex_decomposition(gd)
        self.assertTrue(ok, d)

    def test_commuting_mass_term_and_dispersion(self):
        ok, d = T.commuting_mass_term(algebra())
        self.assertTrue(ok, d)
        self.assertEqual([d[k]["S"] for k in ("e0+e4", "e8+e12", "e0+ie4")], ["-2", "2", "0"])
        ok, d = T.flat_dispersion(algebra())
        self.assertTrue(ok, d)
        self.assertEqual((d["dimensionOnShell_m1_k11234"], d["dimensionOffShell_k4_3"]), (8, 0))


