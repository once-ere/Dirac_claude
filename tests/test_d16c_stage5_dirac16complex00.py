class GeometryAndVariationTests(unittest.TestCase):

    def test_g4_frame_matches_export_and_variation_closed_form(self):
        th = theory()
        E0 = T.g4_frame_data(1)[0]
        if th is not None:
            self.assertEqual([[int(v) for v in row] for row in E0], th["testGeometries"]["G4"]["E0"])
        rec = T.Recorder()
        d = T.check_g4_generic(geos(), rec)
        self.assertTrue(rec.checks["S5_geometry_G4Generic"], d)
        self.assertEqual((d["gUpper44"], d["scalarCurvature"]), ("-49", "82754"))
        geo = geos().g4(1)
        dom = geo.dom
        m, lam = dom.frac(3, 7), dom.frac(5, 11)
        off = T.lcg_field_data(61200)
        on = T.lcg_field_data(61250)
        psi = T.jet_from_derivatives(off[0], off[1], off[2], dom)
        chi = T.jet_from_derivatives(off[3], off[4], off[5], dom)
        psi_on, chi_on = T.G.solve_onshell(geo, T.jet_from_derivatives(on[0], on[1], on[2], dom),
                                           T.jet_from_derivatives(on[3], on[4], on[5], dom), m, lam, max_order=1)
        dd, _ = T.vielbein_variation_point(geo, psi, chi, m, lam, psi_on, chi_on, all_directions=False)
        self.assertTrue(all(v for v in dd.values() if isinstance(v, bool)), dd)
        # negative control: a wrong closed form (dropping the K term of dL/de) breaks the linearisation check
        lean = T.LeanLagrangian(geo, psi, chi, m, lam)
        good = lean.closed_form_dLde()
        e_d = [[T.Dual(lean.e0[i][j], 1 if (i, j) == (0, 1) else 0) for j in range(8)] for i in range(8)]
        self.assertTrue(dom.is_zero(lean.value(e=e_d)[0].b - good[0][1]))
        self.assertFalse(dom.is_zero(lean.value(e=e_d)[0].b - good[0][1] * 2))


