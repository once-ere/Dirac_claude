# Are the y-ODE matrices simultaneously block-diagonalizable into 4x4 blocks? check: algebra generated by A0,A1,A4 dimension
def algebra_dim(gens):
    basis=[np.eye(16)]
    frontier=[np.eye(16)]
    while frontier:
        new=[]
        for Bm in frontier:
            for G in gens:
                Mx=Bm@G
                # test independence
                V=np.array([b.flatten() for b in basis+[Mx]])
                if np.linalg.matrix_rank(V,tol=1e-9)>len(basis):
                    basis.append(Mx); new.append(Mx)
        frontier=new
    return len(basis)
