def commutant_dim(mats):
    n=16; rows=[]
    for M in mats:
        # X M - M X = 0, X flattened row-major: (I kron M^T - M kron I) vec? use explicit
        L=np.kron(np.eye(n),M.T)-np.kron(M,np.eye(n))  # acts on vec(X) with vec row-major? use column-major consistent: vec(XM)= (M^T kron I) vec(X), vec(MX)=(I kron M)vec(X)
        L=np.kron(M.T,np.eye(n))-np.kron(np.eye(n),M)
        rows.append(L)
    L=np.vstack(rows); s=np.linalg.svd(L,compute_uv=False); return int(np.sum(s<1e-9))
