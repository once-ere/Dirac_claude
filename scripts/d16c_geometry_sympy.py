#!/usr/bin/env python3
"""Exact, sympy-based geometry engine for dirac16complex.

This module is an independent (non-Wolfram) implementation of the machinery fixed
in CONTRACT.md sections 1 and 4-7:

* the notebook gammas ``gamma^a := T16^A[a]`` built from the split-octonion
  blocks ``tau``/``taubar`` with sympy Integer matrices;
* ``C := sigma16 = gamma^0 gamma^1 gamma^2 gamma^3`` and ``S^{ab} = [gamma^a,gamma^b]/4``;
* vielbein ``e_mu^a`` (rows mu), metric, Levi-Civita Christoffels, the canonical
  spin connection ``omega_mu^a_b = e_b^nu (Gamma^rho_{mu nu} e_rho^a - d_mu e_nu^a)``
  and, independently, the same connection from the anholonomy (Ricci rotation)
  formula, which never uses Christoffels;
* ``Omega_mu = (1/2) omega_{mu ab} S^{ab}`` with ``omega_{mu ab} = eta_ac omega_mu^c_b``
  and the notebook contraction ``(1/2) omega_mu^a_b S^{ab}``;
* Riemann tensor, Ricci scalar, Einstein tensor, spinor curvature;
* the dirac16complex Lagrangian of CONTRACT section 5 (commuting proxy for the
  bilinear part), Euler-Lagrange derivatives in jet space, and the covariant
  energy-momentum tensor of CONTRACT section 7.

Exactness
---------
Everything is computed with exact arithmetic: sympy ``QQ`` (gmpy2 ``mpq``) for
rational evaluation points, and sympy rational-function fields
``QQ(w, c, E, A1, A2, A3, H)`` (or fields of symbolic metric components) for
symbolic evaluation.  No floating point number is created anywhere; the helper
``assert_exact`` is used by the verifiers to prove that.

Jets
----
Identities involving arbitrary functions are checked in jet space: every
quantity is represented by its truncated Taylor polynomial around the evaluation
point ``p`` (class ``TJet``), with exact coefficients.  The vielbein jets are
obtained by exact symbolic differentiation with sympy followed by exact
substitution of the evaluation point; all other jets follow by exact truncated
power-series arithmetic (products, matrix inverse by the Neumann series,
determinant by exp(tr log)).  Field jets (Psi_a, d_mu Psi_a, d_mu d_nu Psi_a)
are independent exact random rationals drawn from fixed seeds.

Conventions (CONTRACT.md): zero-based indices; eta = diag(1,1,1,1,-1,-1,-1,-1);
x4 is the evolution time; Taylor coefficient for the sorted multi-index
``alpha`` is ``d^alpha f(p) / alpha!``.
"""

