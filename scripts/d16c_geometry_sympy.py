class Geometry:
    """All geometric objects of CONTRACT section 4 as exact jets at one point."""

    def __init__(self, e: TJet, gd: GammaData, dom: ExactDomain, name: str,
                 sqrtg_sign: Optional[int] = None, curvature: bool = True):
        self.name = name
        self.dom = dom
        self.gd = gd
        self.e = e
        half = dom.frac(1, 2)
        ETA = gd.ETA
        self.einv = jinv(e, dom)                                    # [a, mu] = e_a^mu
        self.g = jein("mb,nb->mn", jein("ma,ab->mb", e, ETA), e)   # g_mu nu = e_mu^a eta_ab e_nu^b
        self.ginv = jinv(self.g, dom)
        # Christoffel symbols
        dg = self.g.grad()                                           # [l, m, n] = d_l g_mn
        t1 = dg.map(lambda a: np.einsum("mns->smn", a))              # d_m g_ns
        t2 = dg.map(lambda a: np.einsum("nms->smn", a))              # d_n g_ms
        gam1 = (t1 + t2 - dg).scale(half)                            # Gamma_{s m n}
        self.Gamma = jein("rs,smn->rmn", self.ginv, gam1)           # Gamma^r_{mn}
        # canonical spin connection (Christoffel route)
        self.de = e.grad()                                           # [m, n, a] = d_m e_n^a
        inner = jein("rmn,ra->mna", self.Gamma, e) - self.de
        self.omega_mixed = jein("bn,mna->mab", self.einv, inner)    # omega_mu^a_b
        self.omega_low = jein("ac,mcb->mab", ETA, self.omega_mixed)  # omega_{mu a b}
        # independent anholonomy route: omega_{cad} = (T_cda + T_acd - T_dac)/2,
        # T_cda = - e_c^mu e_d^nu (d_mu e_{nu a} - d_nu e_{mu a})
        eL = jein("nb,ba->na", e, ETA)
        deL = eL.grad()                                              # [m, n, a]
        Fm = deL - deL.map(lambda a: np.einsum("nma->mna", a))
        Tt = jein("cm,mna->cna", self.einv, Fm)
        Tt = jein("dn,cna->cda", self.einv, Tt).scale(-1)
        X1 = Tt.map(lambda a: np.einsum("cda->cad", a))
        X2 = Tt.map(lambda a: np.einsum("acd->cad", a))
        X3 = Tt.map(lambda a: np.einsum("dac->cad", a))
        omF = (X1 + X2 - X3).scale(half)                             # omega_{c a d} (frame)
        self.omega_low_anh = jein("mc,cab->mab", e, omF)             # omega_{mu a b}
        ETAinv = ETA  # eta^{-1} = eta
        self.omega_mixed_anh = jein("ac,mcb->mab", ETAinv, self.omega_low_anh)
        # spinor connections
        self.Omega = jein("mab,abij->mij", self.omega_low, gd.S).scale(half)
        self.Omega_nb = jein("mab,abij->mij", self.omega_mixed, gd.S).scale(half)
        # curved gammas gamma^mu = e_a^mu gamma^a
        self.gam = jein("am,aij->mij", self.einv, gd.GAM)
        self.gam_low = jein("mn,nij->mij", self.g, self.gam)
        # sqrt|g| = |det e|
        dete = jdet(e, dom)
        self.det_e = dete
        if sqrtg_sign is None:
            d0 = dete.value()[()]
            sqrtg_sign = 1 if d0 > 0 else -1
        self.sqrtg_sign = sqrtg_sign
        self.sqrtg = dete.scale(sqrtg_sign)
        self.detg = jdet(self.g, dom)
        self.curvature_done = False
        if curvature and self.Gamma.order >= 1:
            self._curvature()

    # -- curvature -----------------------------------------------------------
    def _curvature(self):
        dom = self.dom
        G0 = self.Gamma.value()
        dG = self.Gamma.grad().value()                               # [m, r, n, s] = d_m Gamma^r_ns
        R = (np.einsum("mrns->rsmn", dG) - np.einsum("nrms->rsmn", dG)
             + np.einsum("rml,lns->rsmn", G0, G0) - np.einsum("rnl,lms->rsmn", G0, G0))
        self.Riem = _norm(R)                                          # R^r_{s m n}
        self.Ric = _norm(np.einsum("rsrn->sn", R))
        ginv0 = self.ginv.value()
        self.Rscalar = np.einsum("sn,sn->", ginv0, self.Ric)
        half = dom.frac(1, 2)
        self.Gmixed = _norm(np.einsum("mr,rn->mn", ginv0, self.Ric) - to_identity(8, dom) * (self.Rscalar * half))
        e0 = self.e.value()
        einv0 = self.einv.value()
        Rf = np.einsum("ra,rsmn,bs->abmn", e0, R, einv0)             # R^a_{b m n}
        self.Rframe_mixed = _norm(Rf)
        self.Rframe_low = _norm(np.einsum("ac,cbmn->abmn", self.gd.ETA, Rf))
        # curvature of the frame connection omega
        om0 = self.omega_mixed.value()
        dom_ = self.omega_mixed.grad().value()                       # [m, n, a, b] = d_m omega_n^a_b
        Rw = (np.einsum("mnab->abmn", dom_) - np.einsum("nmab->abmn", dom_)
              + np.einsum("mac,ncb->abmn", om0, om0) - np.einsum("nac,mcb->abmn", om0, om0))
        self.Romega_mixed = _norm(Rw)
        # spinor curvature
        Om0 = self.Omega.value()
        dOm = self.Omega.grad().value()                              # [m, n, i, j] = d_m Omega_n
        F = (np.einsum("mnij->mnij", dOm) - np.einsum("nmij->mnij", dOm)
             + np.einsum("mij,njk->mnik", Om0, Om0) - np.einsum("nij,mjk->mnik", Om0, Om0))
        self.Fspin = _norm(F)
        self.curvature_done = True

    # -- derived checks ------------------------------------------------------
    def vielbein_postulate(self, which: str = "christoffel") -> TJet:
        om = self.omega_mixed if which == "christoffel" else self.omega_mixed_anh
        return self.de - jein("rmn,ra->mna", self.Gamma, self.e) + jein("mab,nb->mna", om, self.e)

    def omega_antisym_defect(self) -> TJet:
        return self.omega_low + self.omega_low.map(lambda a: np.einsum("mab->mba", a))

    def gamma_covariant_derivative(self, notebook: bool = False, max_order: Optional[int] = None) -> TJet:
        """D_mu gamma^nu = d_mu gamma^nu + Gamma^nu_{mu l} gamma^l + [Omega_mu, gamma^nu] as a jet
        (``max_order`` truncates the inputs so that only the requested jet order is computed)."""
        Om = self.Omega_nb if notebook else self.Omega
        gam, Gam = self.gam, self.Gamma
        if max_order is not None:
            gam = gam.truncate(max_order + 1)
            Om = Om.truncate(max_order)
            Gam = Gam.truncate(max_order)
        dgam = gam.grad()                                            # [m, n, i, j] = d_m gamma^n
        gam = gam.truncate(dgam.order)
        conn = jein("nml,lij->mnij", Gam, gam)
        comm = jein("mij,njk->mnik", Om, gam) - jein("nij,mjk->mnik", gam, Om)
        return dgam + conn + comm

    def divergence_identity_defect(self, notebook: bool = False, max_order: Optional[int] = None) -> TJet:
        """sum_mu d_mu(sqrt|g| gamma^mu) - sqrt|g| sum_mu [gamma^mu, Omega_mu] as a jet."""
        Om = self.Omega_nb if notebook else self.Omega
        sg, gam = self.sqrtg, self.gam
        if max_order is not None:
            sg = sg.truncate(max_order + 1)
            gam = gam.truncate(max_order + 1)
            Om = Om.truncate(max_order)
        sg_gam = jmul(sg, gam)                                       # scalar * (8,16,16)
        lhs = sg_gam.grad().map(lambda a: np.einsum("mmij->ij", a))  # sum_mu d_mu (sqrtg gamma^mu)
        gam = gam.truncate(lhs.order)
        comm = jein("mij,mjk->ik", gam, Om) - jein("mij,mjk->ik", Om, gam)
        rhs = jmul(sg.truncate(comm.order), comm)
        return lhs - rhs

    def truncated(self, order: int) -> "TruncatedGeometry":
        """Geometric jets truncated to ``order`` (cached); used to avoid computing unused orders."""
        if not hasattr(self, "_trunc_cache"):
            self._trunc_cache = {}
        if order not in self._trunc_cache:
            self._trunc_cache[order] = TruncatedGeometry(self, order)
        return self._trunc_cache[order]

    def slash_omega(self, notebook: bool = False) -> np.ndarray:
        Om = self.Omega_nb if notebook else self.Omega
        return _norm(np.einsum("mij,mjk->ik", self.gam.value(), Om.value()))


class TruncatedGeometry:
    """Same interface as Geometry for the spinor functions, with jets truncated to one order."""

    def __init__(self, geo: Geometry, order: int):
        self.dom = geo.dom
        self.gd = geo.gd
        self.order = order
        self.gam = geo.gam.truncate(order)
        self.gam_low = geo.gam_low.truncate(order)
        self.Omega = geo.Omega.truncate(order)
        self.Omega_nb = geo.Omega_nb.truncate(order)
        self.sqrtg = geo.sqrtg.truncate(order)
        self.g = geo.g.truncate(order)


