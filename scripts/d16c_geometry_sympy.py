def mat_inv(M: np.ndarray, dom: ExactDomain) -> np.ndarray:
    n = M.shape[0]
    A = [[M[i, j] for j in range(n)] + [dom.one if i == j else dom.zero for j in range(n)] for i in range(n)]
    for col in range(n):
        piv = None
        for r in range(col, n):
            if not dom.is_zero(A[r][col]):
                piv = r
                break
        if piv is None:
            raise ZeroDivisionError("singular matrix")
        A[col], A[piv] = A[piv], A[col]
        pv = A[col][col]
        A[col] = [x / pv for x in A[col]]
        for r in range(n):
            if r != col:
                f = A[r][col]
                if f != 0:
                    A[r] = [x - f * y for x, y in zip(A[r], A[col])]
    return np.array([row[n:] for row in A], dtype=object)


def mat_det(M: np.ndarray, dom: ExactDomain):
    n = M.shape[0]
    A = [[M[i, j] for j in range(n)] for i in range(n)]
    det = dom.one
    for col in range(n):
        piv = None
        for r in range(col, n):
            if not dom.is_zero(A[r][col]):
                piv = r
                break
        if piv is None:
            return dom.zero
        if piv != col:
            A[col], A[piv] = A[piv], A[col]
            det = -det
        pv = A[col][col]
        det = det * pv
        for r in range(col + 1, n):
            f = A[r][col]
            if f != 0:
                q = f / pv
                A[r] = [x - q * y for x, y in zip(A[r], A[col])]
    return det


def symmetric_signature_rational(M: np.ndarray) -> Tuple[int, int, int]:
    """(n_plus, n_minus, n_zero) of a rational symmetric matrix, exactly.

    Uses the exact characteristic polynomial and Descartes' rule of signs, which
    is exact for polynomials whose roots are all real (real symmetric matrix).
    """
    Ms = sp.Matrix(M.shape[0], M.shape[1], lambda i, j: sp.Rational(int(M[i, j].numerator), int(M[i, j].denominator)))
    lam = sp.Symbol("lam")
    p = sp.Poly(Ms.charpoly(lam).as_expr(), lam)
    coeffs = p.all_coeffs()  # highest first
    nzero = 0
    while coeffs and coeffs[-1] == 0:
        coeffs.pop()
        nzero += 1

    def changes(cs):
        s = [c for c in cs if c != 0]
        return sum(1 for u, v in zip(s, s[1:]) if (u > 0) != (v > 0))

    npos = changes(coeffs)
    deg = len(coeffs) - 1
    neg_coeffs = [c * (-1) ** (deg - i) for i, c in enumerate(coeffs)]
    nneg = changes(neg_coeffs)
    return npos, nneg, nzero


