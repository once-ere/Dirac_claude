def g3_vielbein_sympy() -> sp.Matrix:
    """(G3): diagonal Gaussian-normal x4-only vielbein h_i = 1 + x4^2/(i+2), h_4 = 1."""
    h = [1 + X[4] ** 2 / sp.Integer(i + 2) if i != TIME_INDEX else sp.Integer(1) for i in range(8)]
    return sp.diag(*h)


