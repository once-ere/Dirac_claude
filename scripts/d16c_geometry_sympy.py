G2_GENS = (G2_W, G2_C, G2_E, G2_A1, G2_A2, G2_A3, G2_H)
G2_RELATION = G2_W ** 12 + G2_C ** 2 - 1  # sin^2 z + cos^2 z = 1 with sin z = w^6


def make_g2_domain() -> ExactDomain:
    K = QQ.frac_field(*G2_GENS)
    return ExactDomain(K, "QQ(w,c,E,A1,A2,A3,H) mod (w^12+c^2-1)", relations=[G2_RELATION])


def g2_vielbein_zt():
    """Primordial vielbein (CONTRACT section 9) as functions of z = 6 H x0, t = H x4."""
    z, t = sp.symbols("z t")
    a4 = sp.Function("a4")
    s = sp.sin(z)
    h = [sp.cos(z) / s] + [s ** sp.Rational(1, 6) * sp.exp(a4(t))] * 3 + [sp.Integer(1)] + \
        [s ** sp.Rational(1, 6) * sp.exp(-a4(t))] * 3
    return z, t, a4, h


def g2_vielbein_jet(order: int, dom: ExactDomain) -> TJet:
    """Exact jets of the primordial vielbein at a symbolic point.

    d/dx0 = 6H d/dz, d/dx4 = H d/dt.  After symbolic differentiation:
    a4'''(t) -> A3, a4''(t) -> A2, a4'(t) -> A1, a4(t) -> log(E),
    sin z -> w^6, cos z -> c (w > 0), i.e. sin(z)^(1/6) -> w exactly.
    """
    z, t, a4, h = g2_vielbein_zt()
    c = {}
    for alpha in multi_indices(order):
        arr = np.empty((8, 8), dtype=object)
        for i in range(8):
            for j in range(8):
                arr[i, j] = dom.zero
        n0 = alpha.count(0)
        n4 = alpha.count(4)
        if n0 + n4 == len(alpha):
            fact = alpha_factorial(alpha)
            for i in range(8):
                f = h[i]
                if n0:
                    f = sp.diff(f, z, n0)
                if n4:
                    f = sp.diff(f, t, n4)
                f = f * (6 * G2_H) ** n0 * G2_H ** n4 / fact
                f = f.subs(sp.Derivative(a4(t), (t, 3)), G2_A3).subs(sp.Derivative(a4(t), (t, 2)), G2_A2)
                f = f.subs(sp.Derivative(a4(t), t), G2_A1).subs(a4(t), sp.log(G2_E))
                f = f.subs({sp.sin(z): G2_W ** 6, sp.cos(z): G2_C})
                f = sp.powsimp(sp.expand_power_base(f, force=False))
                if f.free_symbols - set(G2_GENS):
                    raise AssertionError("unexpected symbols in G2 jet: %s" % f)
                arr[i, i] = dom.conv(f)
        c[alpha] = arr
    return TJet(order, c)


def generic_diagonal_jet(hvals: Sequence, dh: Dict[Tuple[int, int], object], dom: ExactDomain) -> TJet:
    """Order-1 jet of a diagonal vielbein diag(h) with d_nu h_mu = dh[(mu, nu)]."""
    c = {}
    v = np.empty((8, 8), dtype=object)
    for i in range(8):
        for j in range(8):
            v[i, j] = hvals[i] if i == j else dom.zero
    c[()] = v
    for nu in range(8):
        a = np.empty((8, 8), dtype=object)
        for i in range(8):
            for j in range(8):
                a[i, j] = dom.zero
        for mu in range(8):
            a[mu, mu] = dh.get((mu, nu), dom.zero)
        c[(nu,)] = a
    return TJet(1, c)


