def mathematica_signature(seq: Sequence[int]) -> int:
    seq = list(seq)
    if len(set(seq)) < len(seq):
        return 0
    sign = 1
    for i in range(len(seq)):
        for j in range(i + 1, len(seq)):
            if seq[i] > seq[j]:
                sign = -sign
    return sign


def notebook_gamma_sympy():
    """Return (gammas, sigma16, tau, taubar, sigma8) as sympy Integer matrices.

    Qa[h,p,q] = Signature[{h,p,q,4}], Qb[h,p,q] = d_{p4} d_{qh} - d_{ph} d_{q4}
    (1-based p,q,h as in the notebook), s4 = Qa - Qb, t4 = Qa + Qb,
    tau[0] = I8, tau[h] = [[0,s4],[s4,0]], tau[7-h] = [[0,t4],[-t4,0]] (h=1..3),
    tau[7] = tau1...tau6, sigma = [[0,I4],[I4,0]], taubar[A] = sigma tau[A]^T sigma,
    gamma^a = [[0, taubar[a]], [tau[a], 0]].
    """
    I4 = sp.eye(4)
    I8 = sp.eye(8)
    Z4 = sp.zeros(4, 4)
    Z8 = sp.zeros(8, 8)

    def delta(i, j):
        return 1 if i == j else 0

    def Qa(h, p, q):
        return mathematica_signature([h, p, q, 4])

    def Qb(h, p, q):
        return delta(p, 4) * delta(q, h) - delta(p, h) * delta(q, 4)

    s4 = {h: sp.Matrix(4, 4, lambda p, q: Qa(h, p + 1, q + 1) - Qb(h, p + 1, q + 1)) for h in (1, 2, 3)}
    t4 = {h: sp.Matrix(4, 4, lambda p, q: Qa(h, p + 1, q + 1) + Qb(h, p + 1, q + 1)) for h in (1, 2, 3)}
    tau = {0: I8}
    for h in (1, 2, 3):
        tau[h] = sp.Matrix(sp.BlockMatrix([[Z4, s4[h]], [s4[h], Z4]]))
        tau[7 - h] = sp.Matrix(sp.BlockMatrix([[Z4, t4[h]], [-t4[h], Z4]]))
    tau[7] = tau[1] * tau[2] * tau[3] * tau[4] * tau[5] * tau[6]
    sig = sp.Matrix(sp.BlockMatrix([[Z4, I4], [I4, Z4]]))
    taub = {0: I8}
    for A in range(1, 8):
        taub[A] = sig * tau[A].T * sig
    gam = [sp.Matrix(sp.BlockMatrix([[Z8, taub[A]], [tau[A], Z8]])) for A in range(8)]
    sig16 = sp.Matrix(sp.BlockMatrix([[-sig, Z8], [Z8, sig]]))
    return gam, sig16, tau, taub, sig


class GammaData:
    """Notebook gammas, C, S^{ab}, eta, chirality as exact domain arrays."""

    def __init__(self, dom: ExactDomain):
        self.dom = dom
        gam_s, sig16_s, tau_s, taub_s, sig_s = notebook_gamma_sympy()
        self.gam_sympy = gam_s
        self.sig16_sympy = sig16_s
        self.GAM = np.stack([to_obj(g.tolist(), dom) for g in gam_s])  # (8,16,16)
        self.C = to_obj((gam_s[0] * gam_s[1] * gam_s[2] * gam_s[3]).tolist(), dom)
        self.SIG16 = to_obj(sig16_s.tolist(), dom)
        self.ID16 = to_obj(sp.eye(16).tolist(), dom)
        self.ETA = to_obj(sp.diag(*ETA_DIAG).tolist(), dom)
        quarter = dom.frac(1, 4)
        S = np.empty((8, 8, 16, 16), dtype=object)
        for a in range(8):
            for b in range(8):
                S[a, b] = (self.GAM[a].dot(self.GAM[b]) - self.GAM[b].dot(self.GAM[a])) * quarter
        self.S = S
        chi = self.ID16
        for a in range(8):
            chi = chi.dot(self.GAM[a])
        self.CHI = chi


