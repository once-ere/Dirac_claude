def g1_vielbein_sympy() -> sp.Matrix:
    """(G1): e_mu^a = delta + P_mu^a, the generic non-diagonal test vielbein."""
    R = sp.Rational

    def P(mu, a):
        if mu != a:
            return (R(1, 10) * ((mu + 1) * X[a] - (a + 1) * X[mu]) + R(1, 20) * X[mu] * X[a]
                    + R(1, 30) * X[(mu + a) % 8] ** 2)
        return R(1, 10) * X[mu] ** 2 + R(1, 40) * X[(mu + 1) % 8]

    return sp.Matrix(8, 8, lambda mu, a: (1 if mu == a else 0) + P(mu, a))


