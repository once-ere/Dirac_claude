def multi_indices(order: int, n: int = DIM) -> List[Tuple[int, ...]]:
    out: List[Tuple[int, ...]] = [()]
    for k in range(1, order + 1):
        out.extend(itertools.combinations_with_replacement(range(n), k))
    return out


def alpha_factorial(alpha: Tuple[int, ...]) -> int:
    f = 1
    for i in set(alpha):
        f *= math.factorial(alpha.count(i))
    return f


class TJet:
    """Truncated Taylor polynomial sum_alpha c_alpha dx^alpha, |alpha| <= order.

    ``c`` maps sorted multi-index tuples to exact object arrays of one common
    shape; the key () (value at the point) is always present.
    """

    __slots__ = ("order", "c")

    def __init__(self, order: int, c: Dict[Tuple[int, ...], np.ndarray]):
        self.order = order
        self.c = c

    @staticmethod
    def const(value, order: int = INF_ORDER) -> "TJet":
        return TJet(order, {(): _norm(value)})

    @property
    def shape(self):
        return self.c[()].shape

    def value(self) -> np.ndarray:
        return self.c[()]

    def coeff(self, alpha: Tuple[int, ...]) -> np.ndarray:
        alpha = tuple(sorted(alpha))
        if alpha in self.c:
            return self.c[alpha]
        return np.zeros(self.shape, dtype=object)

    def partial(self, alpha: Tuple[int, ...]) -> np.ndarray:
        """The partial derivative d^alpha f(p) (= alpha! * Taylor coefficient)."""
        alpha = tuple(sorted(alpha))
        return _norm(self.coeff(alpha) * alpha_factorial(alpha))

    def truncate(self, order: int) -> "TJet":
        order = min(order, self.order)
        return TJet(order, {k: v for k, v in self.c.items() if len(k) <= order})

    def map(self, f: Callable) -> "TJet":
        return TJet(self.order, {k: _norm(f(v)) for k, v in self.c.items()})

    def __add__(self, other) -> "TJet":
        if not isinstance(other, TJet):
            other = TJet.const(other)
        order = min(self.order, other.order)
        c: Dict[Tuple[int, ...], np.ndarray] = {}
        for k, v in self.c.items():
            if len(k) <= order:
                c[k] = v
        for k, v in other.c.items():
            if len(k) <= order:
                c[k] = _norm(c[k] + v) if k in c else v
        return TJet(order, c)

    __radd__ = __add__

    def __neg__(self) -> "TJet":
        return self.map(lambda v: -v)

    def __sub__(self, other) -> "TJet":
        if not isinstance(other, TJet):
            other = TJet.const(other)
        return self + (-other)

    def __rsub__(self, other) -> "TJet":
        return (-self) + other

    def scale(self, s) -> "TJet":
        return self.map(lambda v: v * s)

    def d(self, mu: int) -> "TJet":
        order = self.order - 1 if self.order < INF_ORDER else INF_ORDER
        if order < 0:
            raise ValueError("derivative of an order-0 jet is not available")
        c: Dict[Tuple[int, ...], np.ndarray] = {}
        for k, v in self.c.items():
            cnt = k.count(mu)
            if cnt == 0:
                continue
            lst = list(k)
            lst.remove(mu)
            beta = tuple(lst)
            if len(beta) <= order:
                c[beta] = _norm(v * cnt)
        if () not in c:
            c[()] = np.zeros(self.shape, dtype=object)
        return TJet(order, c)

    def grad(self) -> "TJet":
        """Stack of d_mu (new leading axis mu = 0..7)."""
        ds = [self.d(mu) for mu in range(DIM)]
        order = ds[0].order
        keys = set()
        for dj in ds:
            keys.update(dj.c.keys())
        c = {}
        for k in keys:
            c[k] = _norm(np.stack([dj.coeff(k) for dj in ds]))
        return TJet(order, c)


def jprod(A: TJet, B: TJet, op: Callable) -> TJet:
    order = min(A.order, B.order)
    c: Dict[Tuple[int, ...], np.ndarray] = {}
    for ka, va in A.c.items():
        la = len(ka)
        if la > order:
            continue
        for kb, vb in B.c.items():
            if la + len(kb) > order:
                continue
            k = tuple(sorted(ka + kb))
            r = _norm(op(va, vb))
            c[k] = _norm(c[k] + r) if k in c else r
    if () not in c:
        c[()] = _norm(op(A.value(), B.value()))
    return TJet(order, c)


def jein(spec: str, A, B) -> TJet:
    """einsum product of two jets (either may be a constant array)."""
    if not isinstance(A, TJet):
        A = TJet.const(A)
    if not isinstance(B, TJet):
        B = TJet.const(B)
    if A.order >= INF_ORDER and len(A.c) == 1:
        a0 = A.value()
        return B.map(lambda v: np.einsum(spec, a0, v))
    if B.order >= INF_ORDER and len(B.c) == 1:
        b0 = B.value()
        return A.map(lambda v: np.einsum(spec, v, b0))
    return jprod(A, B, lambda a, b: np.einsum(spec, a, b))


def jmul(A, B) -> TJet:
    """Elementwise/scalar product of jets (broadcasting)."""
    if not isinstance(A, TJet):
        A = TJet.const(A)
    if not isinstance(B, TJet):
        B = TJet.const(B)
    return jprod(A, B, lambda a, b: a * b)


def jet_zero_like(order: int, shape) -> TJet:
    return TJet(order, {(): np.zeros(shape, dtype=object)})


def jinv(A: TJet, dom: ExactDomain) -> TJet:
    """Inverse of a square-matrix jet: sum_k (-A0^{-1} N)^k A0^{-1}."""
    A0 = A.value()
    n = A0.shape[0]
    A0i = mat_inv(A0, dom)
    N = A - TJet.const(A0)
    Xj = jein("ij,jk->ik", -A0i, N)
    res = TJet.const(A0i, order=A.order)
    term = TJet.const(to_identity(n, dom), order=A.order)
    for _ in range(1, A.order + 1 if A.order < INF_ORDER else 1):
        term = jein("ij,jk->ik", term, Xj)
        res = res + jein("ij,jk->ik", term, A0i)
    return res


def to_identity(n: int, dom: ExactDomain) -> np.ndarray:
    I = np.empty((n, n), dtype=object)
    for i in range(n):
        for j in range(n):
            I[i, j] = dom.one if i == j else dom.zero
    return I


def jdet(A: TJet, dom: ExactDomain) -> TJet:
    """det of a square-matrix jet: det(A0) exp(tr log(1 + A0^{-1} N))."""
    A0 = A.value()
    n = A0.shape[0]
    d0 = mat_det(A0, dom)
    K = A.order if A.order < INF_ORDER else 0
    if K == 0:
        return TJet.const(d0, order=A.order)
    A0i = mat_inv(A0, dom)
    Y = jein("ij,jk->ik", A0i, A - TJet.const(A0))
    Lg = jet_zero_like(K, (n, n))
    P = TJet.const(to_identity(n, dom), order=K)
    for k in range(1, K + 1):
        P = jein("ij,jk->ik", P, Y)
        coef = dom.frac((-1) ** (k + 1), k)
        Lg = Lg + P.scale(coef)
    tau = Lg.map(lambda v: np.trace(v))
    Ex = TJet.const(dom.one, order=K)
    T = TJet.const(dom.one, order=K)
    for j in range(1, K + 1):
        T = jmul(T, tau)
        Ex = Ex + T.scale(dom.frac(1, math.factorial(j)))
    return Ex.scale(d0)


def jet_is_zero(J: TJet, dom: ExactDomain, max_order: Optional[int] = None) -> bool:
    for k, v in J.c.items():
        if max_order is not None and len(k) > max_order:
            continue
        if not arr_is_zero(v, dom):
            return False
    return True


