class ExactDomain:
    """Wrapper around an exact sympy domain (QQ or a rational function field).

    ``relations`` is an optional list of sympy polynomial expressions (in the
    field generators) that vanish at the evaluation point; ``is_zero`` first
    tests exact zero and only then reduces the numerator modulo the ideal
    generated by the relations.  Every use of a relation is counted in
    ``relation_uses`` so the reports can state it honestly.
    """

    def __init__(self, K, name: str, relations: Optional[Sequence[sp.Expr]] = None):
        self.K = K
        self.name = name
        self.relation_uses = 0
        self._rel = []
        if relations:
            ring = K.field.ring
            self._rel = [ring.from_expr(r) for r in relations]
        self.one = K.one
        self.zero = K.zero

    def conv(self, x) -> object:
        """Convert a sympy number/expression (or int) into the domain."""
        if isinstance(x, int):
            return self.K.convert(x)
        return self.K.from_sympy(sp.sympify(x))

    def frac(self, p: int, q: int = 1):
        return self.K.convert(QQ(p, q)) if self.K != QQ else QQ(p, q)

    def is_zero(self, x) -> bool:
        if isinstance(x, bool):
            raise TypeError("boolean in exact array")
        if isinstance(x, int):
            return x == 0
        if x == 0:
            return True
        if not self._rel:
            return False
        num = x.numer
        if num.rem(self._rel) == 0:
            self.relation_uses += 1
            return True
        return False

    def to_sympy(self, x) -> sp.Expr:
        if isinstance(x, int):
            return sp.Integer(x)
        return self.K.to_sympy(x)

    def to_str(self, x) -> str:
        e = self.to_sympy(x)
        if e.is_Rational:
            return str(e)
        return str(sp.factor(e))


def make_qq_domain() -> ExactDomain:
    return ExactDomain(QQ, "QQ")


def assert_exact(arr) -> None:
    """Raise if any element is a float/complex (proof that no float leaked in)."""
    a = np.asarray(arr, dtype=object)
    for v in a.flat:
        if isinstance(v, (float, complex)):
            raise AssertionError("floating point value found in exact computation")
        tn = type(v).__name__
        if tn in ("mpfr", "mpc", "Float", "float64", "float32"):
            raise AssertionError("floating point value found: %r" % (v,))


def to_obj(a, dom: ExactDomain) -> np.ndarray:
    """Convert a sympy Matrix / nested list of ints/Rationals into a domain array."""
    arr = np.array(a, dtype=object)
    out = np.empty(arr.shape, dtype=object)
    for idx, v in np.ndenumerate(arr):
        out[idx] = dom.conv(v)
    return out


def arr_is_zero(a, dom: ExactDomain) -> bool:
    return all(dom.is_zero(v) for v in np.asarray(a, dtype=object).flat)


def count_nonzero(a, dom: ExactDomain) -> int:
    return sum(0 if dom.is_zero(v) else 1 for v in np.asarray(a, dtype=object).flat)


def _norm(x) -> np.ndarray:
    return np.asarray(x, dtype=object)


