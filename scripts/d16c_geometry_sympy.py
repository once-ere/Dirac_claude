def vielbein_jet_from_sympy(emat: sp.Matrix, point: Sequence[sp.Rational], order: int, dom: ExactDomain) -> TJet:
    """Exact symbolic differentiation, then exact substitution of the point."""
    subs = dict(zip(X, point))
    c = {}
    for alpha in multi_indices(order):
        arr = np.empty((8, 8), dtype=object)
        fact = alpha_factorial(alpha)
        for i in range(8):
            for j in range(8):
                f = emat[i, j]
                if alpha:
                    f = sp.diff(f, *[X[k] for k in alpha])
                val = f.subs(subs) if f.free_symbols else f
                if not val.is_Rational:
                    raise AssertionError("non-rational jet value")
                val = val / fact
                arr[i, j] = dom.conv(val)
        c[alpha] = arr
    return TJet(order, c)


