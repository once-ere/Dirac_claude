def rand_rational(rng: random.Random, nonzero: bool = True) -> sp.Rational:
    while True:
        p = rng.randint(-9, 9)
        q = rng.randint(1, 9)
        if p != 0 or not nonzero:
            return sp.Rational(p, q)


def random_spinor_jet(rng: random.Random, dom: ExactDomain, order: int,
                      dirs: Optional[Sequence[int]] = None) -> TJet:
    """Independent exact random rational jets Psi_a, d_mu Psi_a, ... (Taylor coeffs)."""
    c = {}
    for alpha in multi_indices(order):
        arr = np.empty((NSPIN,), dtype=object)
        allowed = dirs is None or all(k in dirs for k in alpha)
        for i in range(NSPIN):
            arr[i] = dom.conv(rand_rational(rng)) if allowed else dom.zero
        c[alpha] = arr
    return TJet(order, c)


def covariant_derivative_psi(geo: Geometry, psi: TJet, dpsi: TJet, notebook: bool = False) -> TJet:
    Om = geo.Omega_nb if notebook else geo.Omega
    return dpsi + jein("mij,...j->...mi", Om, psi)


def covariant_derivative_psibar(geo: Geometry, pb: TJet, dpb: TJet) -> TJet:
    return dpb - jein("...i,mij->...mj", pb, geo.Omega)


def lagrangian_scalar(geo: Geometry, pb: TJet, dpb: TJet, psi: TJet, dpsi: TJet, m, lam) -> Dict[str, TJet]:
    """L_s = (1/2)(Psibar gamma^mu D_mu Psi - (D_mu Psibar) gamma^mu Psi) - m S - (lam/2) S^2.

    pb (Psibar = Psi^dagger C, row), dpb (its partial derivatives) and psi, dpsi
    are passed separately, so partial derivatives with respect to the jet
    variables can be taken by linearity (jet-space Euler-Lagrange).  A leading
    batch axis (``...``) is allowed on either the Psibar slot or the Psi slot.
    """
    dom = geo.dom
    half = dom.frac(1, 2)
    Dpsi = covariant_derivative_psi(geo, psi, dpsi)
    Dpb = covariant_derivative_psibar(geo, pb, dpb)
    t1 = jein("...mj,...mj->...", jein("...i,mij->...mj", pb, geo.gam), Dpsi)   # Psibar gamma^mu D_mu Psi
    t2 = jein("...j,...j->...", jein("...mi,mij->...j", Dpb, geo.gam), psi)      # (D_mu Psibar) gamma^mu Psi
    kin = (t1 - t2).scale(half)
    S = jein("...i,...i->...", pb, psi)
    Ls = kin - S.scale(m) - jmul(S, S).scale(lam * half)
    return {"Dpsi": Dpsi, "Dpb": Dpb, "kin": kin, "S": S, "Ls": Ls}


def psibar_from_chi(geo: Geometry, chi: TJet) -> TJet:
    """Psibar = chi^T C with chi standing for Psi^* (commuting proxy)."""
    return jein("...i,ij->...j", chi, geo.gd.C)


def euler_lagrange_psibar(geo: Geometry, psi: TJet, m, lam=0) -> np.ndarray:
    """EL_a = dL/dchi_a - d_mu dL/d(d_mu chi_a), chi_a := Psi^*_a (commuting proxy).

    L = sqrt|g| L_s is linear in (chi, d chi) for lam = 0, so the partial derivatives
    are the evaluations of L on unit jets (batched): P_a with chi = e_a, d chi = 0;
    Q^mu_a with chi = 0, d_nu chi = delta_{nu mu} e_a.  The total derivative d_mu Q^mu_a
    is the exact derivative of the jet Q^mu_a(x), which carries the x-dependence of
    the geometry and of Psi(x).
    """
    dom = geo.dom
    C = geo.gd.C
    if psi.order < 2:
        raise ValueError("Psi jets of order >= 2 are required (Q^mu_a is needed to first order)")
    dpsi = psi.grad()
    # P (value only): batch over a
    g0 = geo.truncated(0)
    pbP = TJet.const(_norm(C.copy()), order=0)                             # rows: e_a^T C
    dpbP = TJet.const(np.zeros((16, 8, 16), dtype=object), order=0)
    LP = lagrangian_scalar(g0, pbP, dpbP, psi.truncate(0), dpsi.truncate(0), m, lam)["Ls"]
    LP = jmul(g0.sqrtg, LP)
    P = LP.value()                                                         # (16,)
    # Q (first order): batch over (a, mu)
    g1 = geo.truncated(1)
    pbQ = TJet.const(np.zeros((16 * 8, 16), dtype=object), order=1)
    dq = np.zeros((16 * 8, 8, 16), dtype=object)
    for a in range(16):
        for mu in range(8):
            dq[a * 8 + mu, mu, :] = C[a, :]
    dpbQ = TJet.const(dq, order=1)
    LQ = lagrangian_scalar(g1, pbQ, dpbQ, psi.truncate(1), dpsi.truncate(1), m, lam)["Ls"]
    LQ = jmul(g1.sqrtg, LQ)                                                # jet, shape (128,)
    divQ = np.empty((16,), dtype=object)
    for a in range(16):
        s = dom.zero
        for mu in range(8):
            s = s + LQ.d(mu).value()[a * 8 + mu]
        divQ[a] = s
    return _norm(P - divQ)


def euler_lagrange_psi(geo: Geometry, chi: TJet, m, lam=0) -> np.ndarray:
    """EL w.r.t. Psi_a (commuting proxy): dL/dPsi_a - d_mu dL/d(d_mu Psi_a)."""
    dom = geo.dom
    if chi.order < 2:
        raise ValueError("chi jets of order >= 2 are required")
    pb = psibar_from_chi(geo, chi)
    dpb = pb.grad()
    I16 = to_identity(16, dom)
    g0 = geo.truncated(0)
    psiP = TJet.const(I16, order=0)
    dpsiP = TJet.const(np.zeros((16, 8, 16), dtype=object), order=0)
    LP = jmul(g0.sqrtg, lagrangian_scalar(g0, pb.truncate(0), dpb.truncate(0), psiP, dpsiP, m, lam)["Ls"])
    P = LP.value()
    g1 = geo.truncated(1)
    psiQ = TJet.const(np.zeros((128, 16), dtype=object), order=1)
    dq = np.zeros((128, 8, 16), dtype=object)
    for a in range(16):
        for mu in range(8):
            dq[a * 8 + mu, mu, a] = dom.one
    dpsiQ = TJet.const(dq, order=1)
    LQ = jmul(g1.sqrtg, lagrangian_scalar(g1, pb.truncate(1), dpb.truncate(1), psiQ, dpsiQ, m, lam)["Ls"])
    divQ = np.empty((16,), dtype=object)
    for a in range(16):
        s = dom.zero
        for mu in range(8):
            s = s + LQ.d(mu).value()[a * 8 + mu]
        divQ[a] = s
    return _norm(P - divQ)


def dirac_operator(geo: Geometry, psi: TJet, notebook: bool = False) -> TJet:
    """gamma^mu D_mu Psi."""
    Dpsi = covariant_derivative_psi(geo, psi, psi.grad(), notebook=notebook)
    return jein("mij,mj->i", geo.gam, Dpsi)


def field_equations(geo: Geometry, psi: TJet, chi: TJet, m, lam) -> Tuple[TJet, TJet, Dict[str, TJet]]:
    """E = gamma^mu D_mu Psi - (m + U'(S)) Psi, Ebar = (D_mu Psibar) gamma^mu + (m + U'(S)) Psibar,
    U(S) = (lam/2) S^2, S = Psibar Psi, Psibar = chi^T C."""
    pb = psibar_from_chi(geo, chi)
    parts = lagrangian_scalar(geo, pb, pb.grad(), psi, psi.grad(), m, lam)
    S = parts["S"]
    mU = S.scale(lam) + TJet.const(m)                                     # m + U'(S)
    E = jein("mij,mj->i", geo.gam, parts["Dpsi"]) - jmul(mU, psi)
    Ebar = jein("mi,mij->j", parts["Dpb"], geo.gam) + jmul(mU, pb)
    parts["pb"] = pb
    return E, Ebar, parts


def solve_onshell(geo: Geometry, psi: TJet, chi: TJet, m, lam, max_order: int = 1) -> Tuple[TJet, TJet]:
    """Replace the d_4-containing Taylor coefficients of Psi and chi so that the field
    equations hold at the point (max_order=1) or to first order (max_order=2)."""
    dom = geo.dom
    C = geo.gd.C
    psi = TJet(psi.order, {k: v.copy() for k, v in psi.c.items()})
    chi = TJet(chi.order, {k: v.copy() for k, v in chi.c.items()})
    G4 = geo.gam.value()[TIME_INDEX]
    G4i = mat_inv(G4, dom)
    half = dom.frac(1, 2)

    def correct(key, r, rb, factor):
        psi.c[key] = _norm(psi.c[key] - G4i.dot(r) * factor)
        chi.c[key] = _norm(chi.c[key] - (rb.dot(G4i)).dot(C) * factor)

    E, Eb, _ = field_equations(geo, psi, chi, m, lam)
    correct((TIME_INDEX,), E.value(), Eb.value(), dom.one)
    if max_order >= 2:
        E, Eb, _ = field_equations(geo, psi, chi, m, lam)
        for nu in range(8):
            if nu == TIME_INDEX:
                continue
            key = tuple(sorted((nu, TIME_INDEX)))
            correct(key, E.coeff((nu,)), Eb.coeff((nu,)), dom.one)
        E, Eb, _ = field_equations(geo, psi, chi, m, lam)
        correct((TIME_INDEX, TIME_INDEX), E.coeff((TIME_INDEX,)), Eb.coeff((TIME_INDEX,)), half)
    return psi, chi


def emt_covariant(geo: Geometry, pb: TJet, Dpb: TJet, psi: TJet, Dpsi: TJet, Ls: TJet) -> TJet:
    """T_mu nu of CONTRACT section 7 (all indices down)."""
    dom = geo.dom
    A = jein("mj,nj->mn", jein("i,mij->mj", pb, geo.gam_low), Dpsi)       # Psibar gamma_m D_n Psi
    B = jein("mnj,j->mn", jein("mi,nij->mnj", Dpb, geo.gam_low), psi)     # (D_m Psibar) gamma_n Psi
    AT = A.map(lambda a: a.T)
    BT = B.map(lambda a: a.T)
    kin = (A + AT - B - BT).scale(dom.frac(-1, 4))
    return kin + jmul(geo.g, Ls)


def emt_from_fields(geo: Geometry, psi: TJet, chi: TJet, m, lam) -> Dict[str, TJet]:
    pb = psibar_from_chi(geo, chi)
    parts = lagrangian_scalar(geo, pb, pb.grad(), psi, psi.grad(), m, lam)
    T = emt_covariant(geo, pb, parts["Dpb"], psi, parts["Dpsi"], parts["Ls"])
    parts["T"] = T
    parts["pb"] = pb
    return parts


def emt_divergence(geo: Geometry, T: TJet) -> np.ndarray:
    """nabla^mu T_mu nu at the point."""
    ginv0 = geo.ginv.value()
    G0 = geo.Gamma.value()
    dT = T.grad().value()                                                  # [r, m, n] = d_r T_mn
    T0 = T.value()
    cov = dT - np.einsum("lrm,ln->rmn", G0, T0) - np.einsum("lrn,ml->rmn", G0, T0)
    return _norm(np.einsum("mr,rmn->n", ginv0, cov))


def box_psi(geo: Geometry, psi: TJet) -> np.ndarray:
    """g^{mu nu} nabla_mu D_nu Psi = g^{mu nu}(d_mu D_nu Psi + Omega_mu D_nu Psi - Gamma^l_{mu nu} D_l Psi)."""
    Dpsi = covariant_derivative_psi(geo, psi, psi.grad())                  # [n, i]
    dD = Dpsi.grad().value()                                               # [m, n, i]
    Om0 = geo.Omega.value()
    D0 = Dpsi.value()
    G0 = geo.Gamma.value()
    inner = dD + np.einsum("mij,nj->mni", Om0, D0) - np.einsum("lmn,li->mni", G0, D0)
    return _norm(np.einsum("mn,mni->i", geo.ginv.value(), inner))


def jet_to_json_number(x, dom: ExactDomain) -> str:
    return dom.to_str(x)
