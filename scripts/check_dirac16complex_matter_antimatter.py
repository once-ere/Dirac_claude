            dsR = sum(self.dOmega[k, m].dot(self.gup[m]) + self.Omega[m].dot(self.dgup[k, m]) for m in range(8))
            self.Bm[(k,)] = to_lists(C.dot(slash) * dsg[k] + C.dot(ds) * sg)
            self.Bp[(k,)] = to_lists(C.dot(slashR) * dsg[k] + C.dot(dsR) * sg)
