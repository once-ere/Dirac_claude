def el_targets(alg, geo, comps, m, lam, mu3, stat_sign):
    """Closed forms: E^{Psi^*}_a = sqrt|g| (C (gamma^mu D_mu Psi - (m + U'(S)) Psi))_a and
    E^{Psi}_a = s sqrt|g| ((D_mu Psibar) gamma^mu + (m + U'(S)) Psibar)_a with s = +1 (Grassmann,
    left derivative) or -1 (commuting)."""
    P, Ps, dP, dPs = comps["P"], comps["Ps"], comps["dP"], comps["dPs"]
    S = scalar_S(alg, geo, comps)
    _, Up = potential(alg, S, lam, mu3)
    Meff = Up + alg.scalar(m) if m != 0 else Up
    CPsi = matvec_elements(alg, geo.Mc[()], P)                       # sqrt|g| C Psi
    PsbarRow = matvec_elements(alg, [list(r) for r in zip(*geo.Mc[()])], Ps)   # sqrt|g| (Psi^dagger C)_a
    tpsis, tpsi = [], []
    for a in range(16):
        t = alg()
        for mu in range(8):
            t = t + linear_combo(alg, geo.A[mu][()][a], dP[mu])
        t = t + linear_combo(alg, geo.Bm[()][a], P)
        t = t - Meff * CPsi[a]
        tpsis.append(t)
        u = alg()
        for mu in range(8):
            u = u + linear_combo(alg, [geo.A[mu][()][i][a] for i in range(16)], dPs[mu])
        u = u - linear_combo(alg, [geo.Bp[()][i][a] for i in range(16)], Ps)
        u = u + Meff * PsbarRow[a]
        tpsi.append(u.scale(stat_sign))
    return tpsis, tpsi


def linear_combo(alg, coeffs, elems):
    acc = alg()
    for c, e in zip(coeffs, elems):
        if c != 0:
            for mm, cc in e.terms.items():
                acc._iadd_term(mm, cc * c)
    return acc


