def matrix_characters(alg, R, Lam, anti, stat):
    """Matrix criterion (derived in the module docstring): for Psi'(x) = R Psi(Lam x) [or R Psi^*]
    with real R, sum_a R^T C gamma^a R Lam_{ba} = tau C gamma^b and R^T C R = tau_S C give
    K -> eps tau K, S -> eps tau_S S (eps = 1 linear; for antilinear eps = +1 commuting, -1
    Grassmann) and, for diagonal Lam, j^b -> tau Lam_bb j^b (linear) or -eps tau Lam_bb j^b."""
    R = np.array(R, dtype=np.int64)
    RT = R.T
    tau = None
    for b in range(8):
        X = sum(RT @ alg.Cg[a] @ R * Lam[b][a] for a in range(8))
        t = 1 if np.array_equal(X, alg.Cg[b]) else (-1 if np.array_equal(X, -alg.Cg[b]) else 0)
        if t == 0 or (tau is not None and t != tau):
            return None
        tau = t
    XS = RT @ alg.C @ R
    tS = 1 if np.array_equal(XS, alg.C) else (-1 if np.array_equal(XS, -alg.C) else 0)
    if tS == 0:
        return None
    eps = 1 if (not anti or stat == "commuting") else -1
    diagonal = all(Lam[i][j] == 0 for i in range(8) for j in range(8) if i != j)
    q = [(eps * tau * Lam[b][b] * (-1 if anti else 1)) for b in range(8)] if diagonal else None
    return {"sigmaK": eps * tau, "sigmaS": eps * tS, "q": q}


