def frac_inverse(matrix):
    """Exact Gauss-Jordan inverse of a square Fraction matrix (list of lists)."""
    n = len(matrix)
    aug = [[Fraction(v) for v in row] + [Fraction(int(i == j)) for j in range(n)] for i, row in enumerate(matrix)]
    for col in range(n):
        piv = next(r for r in range(col, n) if aug[r][col] != 0)
        aug[col], aug[piv] = aug[piv], aug[col]
        pv = aug[col][col]
        aug[col] = [v / pv for v in aug[col]]
        for r in range(n):
            if r != col and aug[r][col] != 0:
                f = aug[r][col]
                aug[r] = [a - f * b for a, b in zip(aug[r], aug[col])]
    return [row[n:] for row in aug]


def frac_det(matrix):
    n = len(matrix)
    a = [[Fraction(v) for v in row] for row in matrix]
    det = Fraction(1)
    for col in range(n):
        piv = next((r for r in range(col, n) if a[r][col] != 0), None)
        if piv is None:
            return Fraction(0)
        if piv != col:
            a[col], a[piv] = a[piv], a[col]
            det = -det
        det *= a[col][col]
        for r in range(col + 1, n):
            f = a[r][col] / a[col][col]
            if f != 0:
                a[r] = [x - f * y for x, y in zip(a[r], a[col])]
    return det


def obj(array_like):
    return np.array(array_like, dtype=object)


def to_lists(array):
    """numpy object/int array -> nested lists of exact Python numbers."""
    return [[(Fraction(int(v)) if isinstance(v, (int, np.integer)) else v) for v in row] for row in array]


class Geometry:
    """Vielbein e_mu^a(x) = E0 + x^l E1[l] + (1/2) x^l x^k E2[l][k] (rows mu, columns a) and
    the exact values and first derivatives at x = 0 of sqrt|g|, gamma^mu, Omega_mu and the
    Lagrangian coefficient matrices (canonical spin connection of CONTRACT section 4)."""

    def __init__(self, alg, name, E0, E1, E2):
        self.alg = alg
        self.name = name
        eta = obj([[Fraction(ETA[i]) if i == j else Fraction(0) for j in range(8)] for i in range(8)])
        E0 = obj([[Fraction(v) for v in row] for row in E0])
        E1 = obj([[[Fraction(v) for v in row] for row in E1[l]] for l in range(8)])          # [l, mu, a]
        E2 = obj([[[[Fraction(v) for v in row] for row in E2[l][k]] for k in range(8)] for l in range(8)])
        self.E0, self.E1, self.E2 = E0, E1, E2
        Einv = obj(frac_inverse(E0.tolist()))                                                   # [a, mu]
        dEinv = obj([-(Einv.dot(E1[l]).dot(Einv)) for l in range(8)])                          # [k, a, mu]
        g0 = E0.dot(eta).dot(E0.T)
        dg = obj([E1[l].dot(eta).dot(E0.T) + E0.dot(eta).dot(E1[l].T) for l in range(8)])     # [l, mu, nu]
        ddg = obj([[E2[l, k].dot(eta).dot(E0.T) + E1[l].dot(eta).dot(E1[k].T) + E1[k].dot(eta).dot(E1[l].T)
                    + E0.dot(eta).dot(E2[l, k].T) for k in range(8)] for l in range(8)])       # [l, k, mu, nu]
        ginv = Einv.T.dot(eta).dot(Einv)
        dginv = obj([-(ginv.dot(dg[k]).dot(ginv)) for k in range(8)])
        # T[mu, nu, s] = d_mu g_{nu s} + d_nu g_{mu s} - d_s g_{mu nu}
        T = obj([[[dg[m, n, s] + dg[n, m, s] - dg[s, m, n] for s in range(8)] for n in range(8)] for m in range(8)])
        Gam = np.einsum("rs,mns->rmn", ginv, T) * HALF                                          # Gamma^r_{mn}
        dGam = []
        for k in range(8):
            Tk = obj([[[ddg[k, m, n, s] + ddg[k, n, m, s] - ddg[k, s, m, n] for s in range(8)]
                       for n in range(8)] for m in range(8)])
            dGam.append((np.einsum("rs,mns->rmn", dginv[k], T) + np.einsum("rs,mns->rmn", ginv, Tk)) * HALF)
        dGam = obj(dGam)
        # omega_mu^a_b = e_b^nu (Gamma^r_{mu nu} e_r^a - d_mu e_nu^a)
        om = np.einsum("bn,rmn,ra->mab", Einv, Gam, E0) - np.einsum("bn,mna->mab", Einv, E1)
        dom = []
        for k in range(8):
            dom.append(np.einsum("bn,rmn,ra->mab", dEinv[k], Gam, E0) + np.einsum("bn,rmn,ra->mab", Einv, dGam[k], E0)
                       + np.einsum("bn,rmn,ra->mab", Einv, Gam, E1[k]) - np.einsum("bn,mna->mab", dEinv[k], E1)
                       - np.einsum("bn,mna->mab", Einv, E2[k]))
        dom = obj(dom)
        etad = np.array([Fraction(v) for v in ETA], dtype=object)
        omlow = om * etad[None, :, None]
        domlow = dom * etad[None, None, :, None]
        S4 = obj([[alg.S4[a][b].tolist() for b in range(8)] for a in range(8)])                 # 4 S^{ab}
        G = obj([alg.gam[a].tolist() for a in range(8)])
        C = obj(alg.C.tolist())
        self.Omega = np.einsum("mab,abij->mij", omlow, S4) * Fraction(1, 8)                     # [mu, i, j]
        self.dOmega = obj([np.einsum("mab,abij->mij", domlow[k], S4) * Fraction(1, 8) for k in range(8)])
        self.gup = np.einsum("am,aij->mij", Einv, G)                                            # gamma^mu
        self.dgup = obj([np.einsum("am,aij->mij", dEinv[k], G) for k in range(8)])            # [k, mu, i, j]
        self.glow = np.einsum("ma,a,aij->mij", E0, etad, G)                                     # gamma_mu
        det0 = frac_det(E0.tolist())
        sign = 1 if det0 > 0 else -1
        self.sqrtg = sign * det0
        self.dsqrtg = [self.sqrtg * sum(Einv.dot(E1[k])[i, i] for i in range(8)) for k in range(8)]
        self.g0, self.ginv, self.Gam, self.omlow, self.domlow = g0, ginv, Gam, omlow, domlow
        self.Einv, self.dEinv, self.dg = Einv, dEinv, dg
        self.C = C
        # Lagrangian coefficient jets: dict {(): value, (k,): d_k value}
        sg, dsg = self.sqrtg, self.dsqrtg
        slash = sum(self.gup[m].dot(self.Omega[m]) for m in range(8))                         # gamma^mu Omega_mu
        slashR = sum(self.Omega[m].dot(self.gup[m]) for m in range(8))                        # Omega_mu gamma^mu
        self.slash, self.slashR = slash, slashR
        self.A = []
        for m in range(8):
            jet = {(): to_lists(C.dot(self.gup[m]) * sg)}
            for k in range(8):
                jet[(k,)] = to_lists(C.dot(self.gup[m]) * dsg[k] + C.dot(self.dgup[k, m]) * sg)
            self.A.append(jet)
        self.Bm = {(): to_lists(C.dot(slash) * sg)}
        self.Bp = {(): to_lists(C.dot(slashR) * sg)}
        self.Mc = {(): to_lists(C * sg)}
        self.sq = {(): sg}
        for k in range(8):
            ds = sum(self.dgup[k, m].dot(self.Omega[m]) + self.gup[m].dot(self.dOmega[k, m]) for m in range(8))
            dsR = sum(self.dOmega[k, m].dot(self.gup[m]) + self.Omega[m].dot(self.dgup[k, m]) for m in range(8))
            self.Bm[(k,)] = to_lists(C.dot(slash) * dsg[k] + C.dot(ds) * sg)
            self.Bp[(k,)] = to_lists(C.dot(slashR) * dsg[k] + C.dot(dsR) * sg)
            self.Mc[(k,)] = to_lists(C * dsg[k])
            self.sq[(k,)] = dsg[k]

    def matrix_checks(self):
        """Exact consistency of the geometry at x = 0."""
        out = {}
        out["inverseMetric"] = all(v == (1 if i == j else 0) for i, row in enumerate(self.ginv.dot(self.g0))
                                   for j, v in enumerate(row))
        out["omegaAntisymmetric"] = all(self.omlow[m, a, b] == -self.omlow[m, b, a]
                                        for m in range(8) for a in range(8) for b in range(8)) and \
            all(self.domlow[k, m, a, b] == -self.domlow[k, m, b, a]
                for k in range(8) for m in range(8) for a in range(8) for b in range(8))
        ok = True
        for m in range(8):
            for n in range(8):
                val = self.dgup[m, n] + sum(self.Gam[n, m, l] * self.gup[l] for l in range(8)) + \
                    self.Omega[m].dot(self.gup[n]) - self.gup[n].dot(self.Omega[m])
                ok = ok and all(v == 0 for v in val.flat)
        out["gammaCovariantlyConstant"] = ok
        lhs = sum(self.gup[m] * self.dsqrtg[m] + self.dgup[m, m] * self.sqrtg for m in range(8))
        rhs = (self.slash - self.slashR) * self.sqrtg
        out["divergenceIdentity"] = all(v == 0 for v in (lhs - rhs).flat)
        out["gammaMuOmegaMuNonzeroEntries"] = int(sum(1 for v in self.slash.flat if v != 0))
        out["riemannProxyOmegaGradientNonzero"] = int(sum(1 for v in self.dOmega.flat if v != 0))
        return out


def random_matrix(rng, lo, hi, density=1.0):
    return [[(rng.randint(lo, hi) if rng.random() < density else 0) for _ in range(8)] for _ in range(8)]


def geometry_generic(alg, seed=SEED):
    """G_A: a non-diagonal curved vielbein with space-space, space-time and time-time mixing."""
    rng = random.Random(seed)
    E0 = [[int(i == j) for j in range(8)] for i in range(8)]
    for (i, j, v) in ((0, 4, 1), (1, 5, -1), (2, 3, 1), (4, 6, 1), (3, 7, -1), (5, 6, 1), (0, 2, -1), (6, 7, 1)):
        E0[i][j] = v                                               # strictly upper triangular: det = 1
    E1 = [random_matrix(rng, -1, 1, 0.6) for _ in range(8)]
    E2 = [[None] * 8 for _ in range(8)]
    for l in range(8):
        for k in range(l, 8):
            E2[l][k] = random_matrix(rng, -1, 1, 0.3)
            E2[k][l] = E2[l][k]
    return Geometry(alg, "G_A_generic_nondiagonal", E0, E1, E2)


