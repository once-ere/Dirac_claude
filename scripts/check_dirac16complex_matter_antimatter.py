        psi, psik = field(vecs, norms, betas)
        car_plus = car_matrix(psi, psik, Bm * P)
        Hp, Qp, Sp = bil(psik, Bm * hp, psi), bil(psik, Bm, psi), bil(psik, Cm, psi)
        # the image field on the same Fock space and state
