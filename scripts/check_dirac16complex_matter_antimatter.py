def jet_total_derivative(alg, jet, js, mu):
    """(d_mu F)(0) = explicit coefficient derivative + derivation on the field jets."""
    return jet.get((mu,), alg()) + js.total_derivative(jet[()], mu)


def euler_lagrange_generic(alg, Ljet, js, species):
    """E_a = d_L L/d theta_{s,a} - sum_mu d_mu (d_L L/d theta_{s,a;mu}) at the point (own code)."""
    res = []
    for a in range(16):
        g0 = js.idx(species, a)
        E = Ljet[()].left_derivative(g0)
        for mu in range(8):
            g = js.idx(species, a, (mu,))
            pi_val = Ljet[()].left_derivative(g)
            pi_mu = Ljet[(mu,)].left_derivative(g)
            E = E - (pi_mu + js.total_derivative(pi_val, mu))
        res.append(E)
    return res


def transform_components(alg, comps, R, anti=False, Lam=None, phase=None):
    """Psi'(x) = R Psi(Lam x) (linear) or R Psi^*(Lam x) (antilinear); R an exact matrix (Python
    numbers), Lam an 8 x 8 matrix (None = identity).  Returns the jets of Psi' at x = 0 as
    algebra elements (Psi'^* uses the complex conjugate matrix)."""
    Rl = [[v for v in row] for row in R]
    if phase is not None:
        Rl = [[v * phase for v in row] for row in Rl]
    Rc = [[conj_scalar(v) for v in row] for row in Rl]
    if Lam is None:
        Lam = [[int(i == j) for j in range(8)] for i in range(8)]
    src, srcs = ("Ps", "P") if anti else ("P", "Ps")
    dsrc, dsrcs = ("dPs", "dP") if anti else ("dP", "dPs")
    P = matvec_elements(alg, Rl, comps[src])
    Ps = matvec_elements(alg, Rc, comps[srcs])
    RdP = [matvec_elements(alg, Rl, comps[dsrc][b]) for b in range(8)]
    RdPs = [matvec_elements(alg, Rc, comps[dsrcs][b]) for b in range(8)]
    dP, dPs = [], []
    for a in range(8):
        acc = [alg() for _ in range(16)]
        accs = [alg() for _ in range(16)]
        for b in range(8):
            lv = Lam[b][a]
            if lv != 0:
                acc = add_elements(acc, scale_elements(RdP[b], lv))
                accs = add_elements(accs, scale_elements(RdPs[b], lv))
        dP.append(acc)
        dPs.append(accs)
    return {"P": P, "Ps": Ps, "dP": dP, "dPs": dPs}


def conj_scalar(c):
    return c.conjugate() if isinstance(c, GaussianRational) else c


def emt(alg, geo, comps, m, lam):
    """T_{mu nu} at the point (STAGE5_SPEC section 2 / CONTRACT section 7), list of 36 (mu <= nu)."""
    P, Ps, dP, dPs = comps["P"], comps["Ps"], comps["dP"], comps["dPs"]
    C = geo.C
    Om = [to_lists(geo.Omega[mu]) for mu in range(8)]
    DP = [add_elements(dP[nu], matvec_elements(alg, Om[nu], P)) for nu in range(8)]
    Ct = to_lists(C.T)
    DPb = []
    for nu in range(8):
        COmT = to_lists(C.dot(geo.Omega[nu]).T)
        DPb.append(add_elements(matvec_elements(alg, Ct, dPs[nu]), scale_elements(matvec_elements(alg, COmT, Ps), -1)))
    L, K, S = lagrangian(alg, geo, comps, m, lam, 0, keys=[()])
    Ls = L[()].scale(Fraction(1) / geo.sqrtg)
    Cgl = [to_lists(C.dot(geo.glow[mu])) for mu in range(8)]
    gl = [to_lists(geo.glow[mu]) for mu in range(8)]
    out = {}
    for mu in range(8):
        for nu in range(mu, 8):
            br = form(alg, Cgl[mu], Ps, DP[nu]) + form(alg, Cgl[nu], Ps, DP[mu]) \
                - form(alg, gl[nu], DPb[mu], P) - form(alg, gl[mu], DPb[nu], P)
            T = br.scale(Fraction(-1, 4)) + Ls.scale(geo.g0[mu, nu])
            out[(mu, nu)] = T
    return out


def derivative_table(alg, F):
    """{g: d_L F / d theta_g} for every generator g of F, in one pass (both statistics)."""
    out = {}
    if alg is Grassmann:
        for m, c in F.terms.items():
            for pos, g in enumerate(m):
                d = out.setdefault(g, Grassmann())
                d._iadd_term(m[:pos] + m[pos + 1:], c if pos % 2 == 0 else -c)
    else:
        for m, c in F.terms.items():
            seen = set()
            for pos, g in enumerate(m):
                if g in seen:
                    continue
                seen.add(g)
                d = out.setdefault(g, CPoly())
                d._iadd_term(m[:pos] + m[pos + 1:], c * m.count(g))
    return out


def euler_lagrange_fast(alg, Ljet, js, species):
    """Same as euler_lagrange_generic, with one derivative table per jet part."""
    tables = {key: derivative_table(alg, Ljet[key]) for key in JET_KEYS}
    empty = alg()
    res = []
    for a in range(16):
        E = tables[()].get(js.idx(species, a), empty).copy()
        for mu in range(8):
            g = js.idx(species, a, (mu,))
            E = E - (tables[(mu,)].get(g, empty) + js.total_derivative(tables[()].get(g, empty), mu))
        res.append(E)
    return res


