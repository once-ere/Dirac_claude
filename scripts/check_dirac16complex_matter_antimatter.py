def sign_relation(new, old):
    """+1 if new == old, -1 if new == -old, 0 otherwise; None if old is zero."""
    if old.nterms() == 0:
        return None
    if elements_equal(new, old):
        return 1
    if elements_equal(new, -old):
        return -1
    return 0


