def derivative_table(alg, F):
    """{g: d_L F / d theta_g} for every generator g of F, in one pass (both statistics)."""
    out = {}
    if alg is Grassmann:
        for m, c in F.terms.items():
            for pos, g in enumerate(m):
                d = out.setdefault(g, Grassmann())
                d._iadd_term(m[:pos] + m[pos + 1:], c if pos % 2 == 0 else -c)
    else:
        for m, c in F.terms.items():
            seen = set()
            for pos, g in enumerate(m):
                if g in seen:
                    continue
                seen.add(g)
                d = out.setdefault(g, CPoly())
                d._iadd_term(m[:pos] + m[pos + 1:], c * m.count(g))
    return out


def euler_lagrange_fast(alg, Ljet, js, species):
    """Same as euler_lagrange_generic, with one derivative table per jet part."""
    tables = {key: derivative_table(alg, Ljet[key]) for key in JET_KEYS}
    empty = alg()
    res = []
    for a in range(16):
        E = tables[()].get(js.idx(species, a), empty).copy()
        for mu in range(8):
            g = js.idx(species, a, (mu,))
            E = E - (tables[(mu,)].get(g, empty) + js.total_derivative(tables[()].get(g, empty), mu))
        res.append(E)
    return res


