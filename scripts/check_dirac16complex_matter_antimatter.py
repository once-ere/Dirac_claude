def el_targets(alg, geo, comps, m, lam, mu3, stat_sign):
    """Closed forms: E^{Psi^*}_a = sqrt|g| (C (gamma^mu D_mu Psi - (m + U'(S)) Psi))_a and
    E^{Psi}_a = s sqrt|g| ((D_mu Psibar) gamma^mu + (m + U'(S)) Psibar)_a with s = +1 (Grassmann,
    left derivative) or -1 (commuting)."""
    P, Ps, dP, dPs = comps["P"], comps["Ps"], comps["dP"], comps["dPs"]
    S = scalar_S(alg, geo, comps)
    _, Up = potential(alg, S, lam, mu3)
    Meff = Up + alg.scalar(m) if m != 0 else Up
    CPsi = matvec_elements(alg, geo.Mc[()], P)                       # sqrt|g| C Psi
    PsbarRow = matvec_elements(alg, [list(r) for r in zip(*geo.Mc[()])], Ps)   # sqrt|g| (Psi^dagger C)_a
    tpsis, tpsi = [], []
    for a in range(16):
        t = alg()
        for mu in range(8):
            t = t + linear_combo(alg, geo.A[mu][()][a], dP[mu])
        t = t + linear_combo(alg, geo.Bm[()][a], P)
        t = t - Meff * CPsi[a]
        tpsis.append(t)
        u = alg()
        for mu in range(8):
            u = u + linear_combo(alg, [geo.A[mu][()][i][a] for i in range(16)], dPs[mu])
        u = u - linear_combo(alg, [geo.Bp[()][i][a] for i in range(16)], Ps)
        u = u + Meff * PsbarRow[a]
        tpsi.append(u.scale(stat_sign))
    return tpsis, tpsi


def linear_combo(alg, coeffs, elems):
    acc = alg()
    for c, e in zip(coeffs, elems):
        if c != 0:
            for mm, cc in e.terms.items():
                acc._iadd_term(mm, cc * c)
    return acc


def check_M1(alg, quick=False, geos=None):
    rec = Recorder("M1")
    if geos is None:
        geos = [geometry_generic(alg)] + ([] if quick else [geometry_diagonal(alg)])
    stats = {}
    for geo in geos:
        gchk = geo.matrix_checks()
        rec.check("geometry_%s" % geo.name, gchk["inverseMetric"] and gchk["omegaAntisymmetric"] and
                  gchk["gammaCovariantlyConstant"] and gchk["divergenceIdentity"] and
                  gchk["gammaMuOmegaMuNonzeroEntries"] > 0, gchk)
        for stat in STATISTICS:
            A = ALGEBRAS[stat]
            tag = "%s_%s" % (stat, geo.name)
            js = JetSpace(["psi", "psis"], max_deriv=2)
            comps = field_components(A, js)
            Ljet, Kjet, S = lagrangian(A, geo, comps, MASS, LAMBDA, MU3, keys=JET_KEYS)
            info = {"lagrangianMonomials": Ljet[()].nterms(), "U": "(lam/2) S^2 + (mu3/3) S^3",
                    "m": str(MASS), "lam": str(LAMBDA), "mu3": str(MU3)}
            # (1) finite U(1): Psi -> e^{i alpha} Psi, cos alpha = 3/5
            I16 = [[Fraction(int(i == j)) for j in range(16)] for i in range(16)]
            tc = transform_components(A, comps, I16, phase=PHASE)
            Lt, Kt, St = lagrangian(A, geo, tc, MASS, LAMBDA, MU3, keys=JET_KEYS)
            u1 = all(elements_equal(Lt[k], Ljet[k]) and elements_equal(Kt[k], Kjet[k]) for k in JET_KEYS) \
                and elements_equal(St, S) and not elements_equal(tc["P"][0], comps["P"][0])
            rec.check("u1Invariance_%s" % tag, u1 and Ljet[()].nterms() > 0)
            # (2) Noether current N^mu = sum_a [dPsi_a dL/d(d_mu Psi_a) + dPsi^*_a dL/d(d_mu Psi^*_a)]
            tables = {key: derivative_table(A, Ljet[key]) for key in JET_KEYS}
            empty = A()
            dpsi = [p.scale(I_UNIT) for p in comps["P"]]
            dpsis = [p.scale(-I_UNIT) for p in comps["Ps"]]
            N = []
            for mu in range(8):
                jet = {}
                for key in JET_KEYS:
                    acc = A()
                    for a in range(16):
                        acc = acc + dpsi[a] * tables[key].get(js.idx("psi", a, (mu,)), empty) + \
                            dpsis[a] * tables[key].get(js.idx("psis", a, (mu,)), empty)
                    jet[key] = acc
                N.append(jet)
            jj = current_jet(A, geo, comps)
            noether_form = all(elements_equal(N[mu][key], jj[mu][key].scale(I_UNIT)) for mu in range(8)
                               for key in JET_KEYS) and all(jj[mu][()].nterms() > 0 for mu in range(8))
            rec.check("noetherCurrentIsISqrtgPsibarGammaPsi_%s" % tag, noether_form)
            # (3) Euler-Lagrange expressions: own code, grassmann_algebra cross-check, closed forms
            Epsi = euler_lagrange_fast(A, Ljet, js, "psi")
            Epsis = euler_lagrange_fast(A, Ljet, js, "psis")
            cross = True
            if A is Grassmann:
                ref_psi = euler_lagrange_all(JetGrassmann(dict(Ljet)), js, "psi")
                ref_psis = euler_lagrange_all(JetGrassmann(dict(Ljet)), js, "psis")
                cross = all(elements_equal(x, y) for x, y in zip(Epsi, ref_psi)) and \
                    all(elements_equal(x, y) for x, y in zip(Epsis, ref_psis))
            if quick is False or A is CPoly:
                slow = euler_lagrange_generic(A, Ljet, js, "psis")
                cross = cross and all(elements_equal(x, y) for x, y in zip(slow, Epsis))
            rec.check("eulerLagrangeCrossCheck_%s" % tag, cross)
            ssign = 1 if A is Grassmann else -1
            tpsis, tpsi = el_targets(A, geo, comps, MASS, LAMBDA, MU3, ssign)
            rec.check("eulerLagrangeClosedForm_%s" % tag,
                      all(elements_equal(Epsis[a], tpsis[a]) and elements_equal(Epsi[a], tpsi[a]) for a in range(16))
                      and all(Epsis[a].nterms() > 0 for a in range(16)))
            # (4) off-shell Noether identity: d_mu N^mu = -sum_a (dPsi_a E^Psi_a + dPsi^*_a E^Psi*_a)
            divN = A()
            for mu in range(8):
                divN = divN + jet_total_derivative(A, N[mu], js, mu)
            rhs = A()
            for a in range(16):
                rhs = rhs - dpsi[a] * Epsi[a] - dpsis[a] * Epsis[a]
            rec.check("noetherIdentity_%s" % tag, elements_equal(divN, rhs) and divN.nterms() > 0)
            # (5) direct: d_mu(sqrt|g| j^mu) = sqrt|g| [(D Psibar) gamma Psi + Psibar gamma D Psi]
            #             = sum_a Psi^*_a E^Psi*_a + s sum_a E^Psi_a Psi_a   (vanishes on shell)
