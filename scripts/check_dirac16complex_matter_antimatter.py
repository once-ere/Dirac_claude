class CPoly:
    """Commutative polynomial in generators; monomials are sorted tuples WITH repetition.
    Same method names as grassmann_algebra.Grassmann, so the Lagrangian code and
    grassmann_algebra.JetSpace.total_derivative work for both statistics."""

    __slots__ = ("terms",)

    def __init__(self, terms=None):
        self.terms = {} if terms is None else terms

    @staticmethod
    def gen(i, coeff=1):
        return CPoly({(i,): coeff}) if coeff != 0 else CPoly()

    @staticmethod
    def scalar(c):
        return CPoly({(): c}) if c != 0 else CPoly()

    def copy(self):
        return CPoly(dict(self.terms))

    def _iadd_term(self, m, c):
        if m in self.terms:
            v = self.terms[m] + c
            if v == 0:
                del self.terms[m]
            else:
                self.terms[m] = v
        elif c != 0:
            self.terms[m] = c

    def __add__(self, other):
        if not isinstance(other, CPoly):
            other = CPoly.scalar(other)
        r = self.copy()
        for m, c in other.terms.items():
            r._iadd_term(m, c)
        return r

    __radd__ = __add__

    def __neg__(self):
        return CPoly({m: -c for m, c in self.terms.items()})

    def __sub__(self, other):
        if not isinstance(other, CPoly):
            other = CPoly.scalar(other)
        return self + (-other)

    def scale(self, s):
        out = {}
        for m, c in self.terms.items():
            v = c * s
            if v != 0:
                out[m] = v
        return CPoly(out)

    def __mul__(self, other):
        if not isinstance(other, CPoly):
            return self.scale(other)
        r = CPoly()
        for m1, c1 in self.terms.items():
            for m2, c2 in other.terms.items():
                r._iadd_term(tuple(sorted(m1 + m2)), c1 * c2)
        return r

    def __rmul__(self, other):
        return self.scale(other)

    def __pow__(self, k):
        r = CPoly.scalar(1)
        for _ in range(k):
            r = r * self
        return r

    def is_zero(self, zero_test=None):
        return len(self.terms) == 0

    def __eq__(self, other):
        if not isinstance(other, CPoly):
            other = CPoly.scalar(other)
        return (self - other).is_zero()

    __hash__ = None

    def nterms(self):
        return len(self.terms)

    def generators(self):
        s = set()
        for m in self.terms:
            s.update(m)
        return s

    def left_derivative(self, k):
        """Ordinary partial derivative (no signs for commuting generators)."""
        out = CPoly()
        for m, c in self.terms.items():
            r = m.count(k)
            if r:
                pos = m.index(k)
                out._iadd_term(m[:pos] + m[pos + 1:], c * r)
        return out

    right_derivative = left_derivative

    def apply_generator_map_derivation(self, gmap):
        out = CPoly()
        for m, c in self.terms.items():
            for pos, g in enumerate(m):
                h = gmap(g)
                if h is None:
                    continue
                out._iadd_term(tuple(sorted(m[:pos] + (h,) + m[pos + 1:])), c)
        return out

    def apply_even_derivation(self, image):
        out = CPoly()
        for m, c in self.terms.items():
            for pos, g in enumerate(m):
                img = image(g)
                if img is None or img.nterms() == 0:
                    continue
                term = CPoly({m[:pos] + m[pos + 1:]: c}) * img
                for mm, cc in term.terms.items():
                    out._iadd_term(mm, cc)
        return out

    def conjugate(self, gconj, cconj=None):
        out = CPoly()
        for m, c in self.terms.items():
            cc = c.conjugate() if isinstance(c, GaussianRational) else c
            out._iadd_term(tuple(sorted(gconj(g) for g in m)), cc)
        return out


