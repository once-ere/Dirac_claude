def check_wolfram_agreement(alg, theory_path, own):
    """Compare the Wolfram theory with the results derived here (independent code, same conventions:
    kappa = sigma_K, sigma = sigma_S, currentSigns = q; Gamma_A = product of gamma^a over A).  Only
    items found in the Wolfram file are compared; the list is recorded in comparedItems."""
    with open(theory_path, "r", encoding="utf-8") as handle:
        theory = json.load(handle)
    rec = Recorder("wolfram")
    compared = []
    compare_m2_intertwiners(alg, rec, theory, own, compared)
    compare_classification_rows(alg, rec, theory, compared)
    compare_m2_summaries(rec, theory, own, compared)
    compare_m3(rec, theory, own, compared)
    compare_m4(rec, theory, own, compared)
    rec.measure("comparedItems", compared)
    ok = rec.ok() and bool(compared)
    return ok, rec


