def potential(alg, S, lam, mu3):
    """U(S) = (lam/2) S^2 + (mu3/3) S^3 and U'(S) = lam S + mu3 S^2."""
    S2 = S * S
    U = S2.scale(lam * HALF)
    Up = S.scale(lam)
    if mu3:
        U = U + (S2 * S).scale(Fraction(mu3) / 3)
        Up = Up + S2.scale(mu3)
    return U, Up


