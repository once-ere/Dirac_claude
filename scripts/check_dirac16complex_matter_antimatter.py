def hermitian_signature_exact(H):
    """(n_+, n_-) of a Hermitian matrix with Gaussian-rational entries: its characteristic
    polynomial has only real roots, so Descartes' rule of signs counts them exactly."""
    x = sp.Symbol("x")
    poly = sp.Poly(sp.expand(H.charpoly(x).as_expr()), x)
    coeffs = [sp.nsimplify(c) for c in poly.all_coeffs()]
    assert all(sp.im(c) == 0 for c in coeffs)

    def changes(cs):
        cs = [c for c in cs if c != 0]
        return sum(1 for a, b in zip(cs, cs[1:]) if (a > 0) != (b > 0))
    deg = poly.degree()
    pos = changes(coeffs)
    neg = changes([c * (-1) ** (deg - i) for i, c in enumerate(coeffs)])
    return pos, neg


