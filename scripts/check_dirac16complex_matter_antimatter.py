def divergence_identity_all_directions(alg, E0, notebook_contraction=False):
    """Proof of d_mu(sqrt|g| gamma^mu) = sqrt|g| [gamma^mu, Omega_mu] and D_mu gamma^nu = 0 at a
    point with e(0) = E0 (integer, |det| = 1) for ARBITRARY first derivatives d_l e_nu^a: both
    sides are linear in the 512 numbers d_l e_nu^a, so it suffices to verify all 512 basis
    directions.  Exact int64 arithmetic after multiplying by 16.  With notebook_contraction=True
    the mixed omega_mu^a_b replaces omega_{mu ab} (negative control; must fail)."""
    E0 = np.array(E0, dtype=np.int64)
    einv_f = frac_inverse(E0.tolist())
    assert all(v.denominator == 1 for row in einv_f for v in row)
    Einv = np.array([[int(v) for v in row] for row in einv_f], dtype=np.int64)
    det0 = int(frac_det(E0.tolist()))
    assert abs(det0) == 1
    eta = np.diag(ETA).astype(np.int64)
    G = np.array(alg.gam, dtype=np.int64)
    S4 = np.array([[alg.S4[a][b] for b in range(8)] for a in range(8)], dtype=np.int64)
    ginv = Einv.T @ eta @ Einv
    npd = 512
    BE = np.zeros((npd, 8, 8, 8), dtype=np.int64)                 # [p, l, nu, a]
    for p in range(npd):
        l, rest = divmod(p, 64)
        nu, a = divmod(rest, 8)
        BE[p, l, nu, a] = 1
    dg = np.einsum("plma,ab,nb->plmn", BE, eta, E0) + np.einsum("ma,ab,plnb->plmn", E0, eta, BE)
    # T[p, m, n, s] = dg[p, m, n, s] + dg[p, n, m, s] - dg[p, s, m, n]
    Tt = dg + np.transpose(dg, (0, 2, 1, 3)) - np.transpose(dg, (0, 2, 3, 1))
    Gam2 = np.einsum("rs,pmns->prmn", ginv, Tt)                   # 2 Gamma^r_{mn}
    om2 = np.einsum("bn,prmn,ra->pmab", Einv, Gam2, E0) - 2 * np.einsum("bn,pmna->pmab", Einv, BE)
    omlow2 = om2 * np.array(ETA, dtype=np.int64)[None, None, :, None]
    antisym = bool(np.array_equal(omlow2, -np.transpose(omlow2, (0, 1, 3, 2))))
    # negative control: the notebook contraction (mixed omega_mu^a_b with S^{ab}, CONTRACT 3.4)
    omega_used = om2 if notebook_contraction else omlow2
    Om16 = np.einsum("pmab,abij->pmij", omega_used, S4)           # 16 Omega_mu
    gup = np.einsum("am,aij->mij", Einv, G)
    dEinv = -np.einsum("ab,plbc,cm->plam", Einv, BE, Einv)        # d_l e_a^mu, [p, l, a, mu]
    dgup = np.einsum("plam,aij->plmij", dEinv, G)                  # d_l gamma^mu
    dsq = np.einsum("ab,plba->pl", Einv, BE)                      # |det| = 1: d_l sqrt|g| = tr(Einv d_l E)
    lhs16 = 16 * (np.einsum("pm,mij->pij", dsq, gup) + np.einsum("pmmij->pij", dgup))
    rhs16 = np.einsum("mij,pmjk->pik", gup, Om16) - np.einsum("pmij,mjk->pik", Om16, gup)
    div_ok = bool(np.array_equal(lhs16, rhs16))
    comm = np.einsum("pmij,njk->pmnik", Om16, gup) - np.einsum("nij,pmjk->pmnik", gup, Om16)
    dgamma16 = 16 * dgup + 8 * np.einsum("pnml,lij->pmnij", Gam2, gup) + comm
    cov_ok = bool(not np.any(dgamma16))
    nontrivial = int(np.count_nonzero(np.any(Om16 != 0, axis=(1, 2, 3))))
    return {"directions": npd, "omegaAntisymmetric": antisym, "divergenceIdentity": div_ok,
            "gammaCovariantlyConstant": cov_ok, "directionsWithNonzeroOmega": nontrivial}


