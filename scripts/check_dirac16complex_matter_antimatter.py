def frac_inverse(matrix):
    """Exact Gauss-Jordan inverse of a square Fraction matrix (list of lists)."""
    n = len(matrix)
    aug = [[Fraction(v) for v in row] + [Fraction(int(i == j)) for j in range(n)] for i, row in enumerate(matrix)]
    for col in range(n):
        piv = next(r for r in range(col, n) if aug[r][col] != 0)
        aug[col], aug[piv] = aug[piv], aug[col]
        pv = aug[col][col]
        aug[col] = [v / pv for v in aug[col]]
        for r in range(n):
            if r != col and aug[r][col] != 0:
                f = aug[r][col]
                aug[r] = [a - f * b for a, b in zip(aug[r], aug[col])]
    return [row[n:] for row in aug]


def frac_det(matrix):
    n = len(matrix)
    a = [[Fraction(v) for v in row] for row in matrix]
    det = Fraction(1)
    for col in range(n):
        piv = next((r for r in range(col, n) if a[r][col] != 0), None)
        if piv is None:
            return Fraction(0)
        if piv != col:
            a[col], a[piv] = a[piv], a[col]
            det = -det
        det *= a[col][col]
        for r in range(col + 1, n):
            f = a[r][col] / a[col][col]
            if f != 0:
                a[r] = [x - f * y for x, y in zip(a[r], a[col])]
    return det


def obj(array_like):
    return np.array(array_like, dtype=object)


def to_lists(array):
    """numpy object/int array -> nested lists of exact Python numbers."""
    return [[(Fraction(int(v)) if isinstance(v, (int, np.integer)) else v) for v in row] for row in array]


class Geometry:
    """Vielbein e_mu^a(x) = E0 + x^l E1[l] + (1/2) x^l x^k E2[l][k] (rows mu, columns a) and
    the exact values and first derivatives at x = 0 of sqrt|g|, gamma^mu, Omega_mu and the
    Lagrangian coefficient matrices (canonical spin connection of CONTRACT section 4)."""

    def __init__(self, alg, name, E0, E1, E2):
        self.alg = alg
        self.name = name
        eta = obj([[Fraction(ETA[i]) if i == j else Fraction(0) for j in range(8)] for i in range(8)])
        E0 = obj([[Fraction(v) for v in row] for row in E0])
        E1 = obj([[[Fraction(v) for v in row] for row in E1[l]] for l in range(8)])          # [l, mu, a]
