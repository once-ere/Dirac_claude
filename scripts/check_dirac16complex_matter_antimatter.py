def form(alg, X, left, right):
    """sum_{i,j} left_i X_ij right_j with the products taken in this order."""
    total = alg()
    for i in range(len(left)):
        if left[i].nterms() == 0:
            continue
        acc = alg()
        for j in range(len(right)):
            c = X[i][j]
            if c != 0:
                for mm, cc in right[j].terms.items():
                    acc._iadd_term(mm, cc * c)
        if acc.nterms():
            prod = left[i] * acc
            for mm, cc in prod.terms.items():
                total._iadd_term(mm, cc)
    return total


def substitute(F, alg, image):
    """Algebra homomorphism theta_g -> image(g) (linear elements), factor order kept."""
    out = alg()
    cache = {}
    for m, c in F.terms.items():
        prod = alg.scalar(c)
        for g in m:
            if g not in cache:
                cache[g] = image(g)
            prod = prod * cache[g]
            if prod.nterms() == 0:
                break
        for mm, cc in prod.terms.items():
            out._iadd_term(mm, cc)
    return out


def elements_equal(a, b):
    return (a - b).is_zero()


def sign_relation(new, old):
    """+1 if new == old, -1 if new == -old, 0 otherwise; None if old is zero."""
    if old.nterms() == 0:
        return None
    if elements_equal(new, old):
        return 1
    if elements_equal(new, -old):
        return -1
    return 0


