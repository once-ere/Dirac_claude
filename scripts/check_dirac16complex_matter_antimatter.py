def coefficients_in(vec, basis):
    """Exact coefficients c with vec = sum_i c_i basis_i (None if vec is not in the span)."""
    M = sp.Matrix([[b[k] for b in basis] for k in range(len(vec))])
    try:
        sol, params = M.gauss_jordan_solve(sp.Matrix([sp.Rational(v.numerator, v.denominator) for v in vec]))
    except ValueError:
        return None
    if params.shape[0]:
        return None
    return [str(sol[i]) for i in range(len(basis))]


def symmetry_rows(kind):
    rows = []
    for i in range(16):
        for j in range(i, 16):
            if kind == "symmetric" and i < j:
                rows.append({i * 16 + j: 1, j * 16 + i: -1})
            elif kind == "antisymmetric":
                rows.append({i * 16 + j: 1, j * 16 + i: 1} if i < j else {i * 16 + i: 1})
    return rows


def invariance_rows(alg, pairs):
    rows = []
    for a, b in pairs:
        S = alg.S4[a][b].tolist()
        St = alg.S4[a][b].T.tolist()
        rows.extend(matrix_equations([(1, St, None), (1, None, S)]))
    return rows


def vector_action(alg, X):
    """l_{cb} with [gamma^c, X] = - sum_b l_{cb} gamma^b (the vector representation of X)."""
    out = [[Fraction(0)] * 8 for _ in range(8)]
    for c in range(8):
        comm = alg.gam[c] @ X - X @ alg.gam[c]
        for b in range(8):
            out[c][b] = -Fraction(int(np.trace(comm @ alg.gam[b])) * ETA[b], 16)
    return out


def derivative_bilinear_rows(alg, pairs):
    """Unknown M: the bilinear Psi^T M gamma^c d_c Psi is invariant under X = S^{ab}:
    X^T M gamma^c + M gamma^c X + sum_b l_{cb} M gamma^b = 0 for every c."""
    rows = []
    for a, b in pairs:
        X4 = alg.S4[a][b]                         # 4 X (homogeneous equations: the scale is irrelevant)
        ell = vector_action(alg, X4)
        for c in range(8):
            terms = [(1, X4.T.tolist(), alg.gam[c].tolist()), (1, None, (alg.gam[c] @ X4).tolist())]
            for bb in range(8):
                if ell[c][bb] != 0:
                    terms.append((ell[c][bb], None, alg.gam[bb].tolist()))
            rows.extend(matrix_equations(terms))
    return rows


