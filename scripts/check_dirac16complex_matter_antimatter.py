def reflection_matrix_for_vector(u):
    """For R = u_a gamma^a (components u_a = u[a], R^2 = n = eta^{ab} u_a u_b): R gamma^a R^{-1} =
    - sum_b N_{ab} gamma^b with N = 1 - 2 eta u u^T / n (an involution); the coordinate map paired
    with R in Psi'(x) = R Psi(Lam x) is Lam = N, Lam_{ba} = delta_ba - 2 eta_bb u_b u_a / n (the
    reflection in the hyperplane orthogonal to the vector with components u^b = eta^{bb} u_b)."""
    n = sum(ETA[a] * u[a] * u[a] for a in range(8))
    return [[Fraction(int(b == a)) - Fraction(2 * ETA[b] * u[b] * u[a], n) for a in range(8)] for b in range(8)], n


