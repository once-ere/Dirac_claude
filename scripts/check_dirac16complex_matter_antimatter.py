def matvec_elements(alg, mat, elems):
    """(mat . elems)_i = sum_j mat[i][j] elems[j] for algebra elements (a linear combination)."""
    out = []
    for i in range(len(mat)):
        acc = alg()
        for j in range(len(elems)):
            c = mat[i][j]
            if c != 0:
                for mm, cc in elems[j].terms.items():
                    acc._iadd_term(mm, cc * c)
        out.append(acc)
    return out


