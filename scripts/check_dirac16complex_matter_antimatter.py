def find_key(document, name):
    """All values stored under key ``name`` anywhere in a JSON document."""
    found = []
    if isinstance(document, dict):
        for k, v in document.items():
            if k == name:
                found.append(v)
            found.extend(find_key(v, name))
    elif isinstance(document, list):
        for v in document:
            found.extend(find_key(v, name))
    return found


def wolfram_summary_from_rows(rows):
    """The Wolfram M2 symmetrySummary items, evaluated with the definitions stated there, from our rows."""
    def exists(pred, anti, stat, flag="exact"):
        for r in rows:
            if r["antilinear"] == anti and pred(r["axes"]):
                mc = r[stat]
                ok = (mc["sigmaK"] == 1 and mc["sigmaS"] == 1) if flag == "exact" else mc["sigmaK"] == 1
                if ok:
                    return True
        return False

    def single(ax):
        return len(ax) == 1 and ax[0] <= 3
    out = {}
    for stat in STATISTICS:
        out[stat] = {
            "C (R empty, antilinear) exact": exists(lambda ax: ax == [], True, stat),
            "C exact at m = 0": exists(lambda ax: ax == [], True, stat, "m0"),
            "P (one space-like reflection, linear) exact": exists(single, False, stat),
            "P exact at m = 0": exists(single, False, stat, "m0"),
            "CP (one space-like reflection, antilinear) exact": exists(single, True, stat),
            "P3 (x1,x2,x3, linear) exact": exists(lambda ax: ax == [1, 2, 3], False, stat),
            "CP3 (x1,x2,x3, antilinear) exact": exists(lambda ax: ax == [1, 2, 3], True, stat),
            "T (x4, linear) exact": exists(lambda ax: ax == [4], False, stat),
            "T (x4, antilinear) exact": exists(lambda ax: ax == [4], True, stat),
            "CPT (all x, antilinear) exact": exists(lambda ax: ax == list(range(8)), True, stat),
            "CP3T (x1..x4, antilinear) exact": exists(lambda ax: ax == [1, 2, 3, 4], True, stat),
        }
    return out


def first_found(theory, *names):
    for name in names:
        vals = find_key(theory, name)
        if vals:
            return vals[0]
    return None


def matrix_from_json(m):
    """Exact matrix from a Wolfram JSON matrix (integers, rational strings or [re, im] pairs)."""
    def conv(v):
        if isinstance(v, list):
            if v[1] not in (0, "0"):
                raise ValueError("complex entry")
            v = v[0]
        return Fraction(v) if isinstance(v, (int, str)) else Fraction(str(v))
    return [[conv(v) for v in row] for row in m]


