        T = obj([[[dg[m, n, s] + dg[n, m, s] - dg[s, m, n] for s in range(8)] for n in range(8)] for m in range(8)])
        Gam = np.einsum("rs,mns->rmn", ginv, T) * HALF                                          # Gamma^r_{mn}
