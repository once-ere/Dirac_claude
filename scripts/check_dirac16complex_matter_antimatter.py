def permutation_signature(sequence):
    """Mathematica Signature: sign of the sorting permutation, 0 if an entry repeats."""
    items = list(sequence)
    if len(set(items)) != len(items):
        return 0
    sign = 1
    for i in range(len(items)):
        for j in range(i + 1, len(items)):
            if items[i] > items[j]:
                sign = -sign
    return sign


def contract_gammas():
    """gamma^a = [[0, taubar_a], [tau_a, 0]] exactly as in CONTRACT section 1."""
    def qa(h):
        return np.array([[permutation_signature((h, p, q, 4)) for q in range(1, 5)] for p in range(1, 5)],
                        dtype=np.int64)

    def qb(h):
        return np.array([[(1 if (p == 4 and q == h) else 0) - (1 if (p == h and q == 4) else 0)
                          for q in range(1, 5)] for p in range(1, 5)], dtype=np.int64)

    zero4 = np.zeros((4, 4), dtype=np.int64)
    eye4 = np.eye(4, dtype=np.int64)
    tau = {0: np.eye(8, dtype=np.int64)}
    for h in (1, 2, 3):
        s4 = qa(h) - qb(h)
        t4 = qa(h) + qb(h)
        tau[h] = np.block([[zero4, s4], [s4, zero4]])
        tau[7 - h] = np.block([[zero4, t4], [-t4, zero4]])
    tau[7] = tau[1] @ tau[2] @ tau[3] @ tau[4] @ tau[5] @ tau[6]
    sigma = np.block([[zero4, eye4], [eye4, zero4]])
    taubar = {0: np.eye(8, dtype=np.int64)}
    for a in range(1, 8):
        taubar[a] = sigma @ tau[a].T @ sigma
    zero8 = np.zeros((8, 8), dtype=np.int64)
    return [np.block([[zero8, taubar[a]], [tau[a], zero8]]) for a in range(8)]


