def to_qq(v):
    v = Fraction(v)
    return QQ(v.numerator, v.denominator)


def exact_nullspace(rows, ncols):
    """Basis (list of Fraction lists) of {x in QQ^ncols : sum_j row[j] x_j = 0 for every row}.
    ``rows`` is an iterable of dicts {column: rational}."""
    sdm = {}
    for row in rows:
        entries = {j: to_qq(v) for j, v in row.items() if v != 0}
        if entries:
            sdm[len(sdm)] = entries
    if not sdm:
        return [[Fraction(int(i == j)) for j in range(ncols)] for i in range(ncols)]
    basis = DomainMatrix(sdm, (len(sdm), ncols), QQ).nullspace()
    return [[Fraction(int(v.numerator), int(v.denominator)) for v in row] for row in basis.to_list()]


def exact_rank(vectors, ncols):
    """Rank over QQ of a list of Fraction vectors."""
    sdm = {}
    for vec in vectors:
        row = {j: to_qq(v) for j, v in enumerate(vec) if v != 0}
        if row:
            sdm[len(sdm)] = row
    if not sdm:
        return 0
    return DomainMatrix(sdm, (len(sdm), ncols), QQ).rank()


def primitive_integer(vec):
    """Scale a rational vector to coprime integers with the first nonzero entry positive."""
    den = 1
    for v in vec:
        v = Fraction(v)
        den = den * v.denominator // int(np.gcd(den, v.denominator))
    ints = [int(Fraction(v) * den) for v in vec]
    g = 0
    for v in ints:
        g = int(np.gcd(g, abs(v)))
    ints = [v // g for v in ints] if g else ints
    first = next((v for v in ints if v != 0), 0)
    return [-v for v in ints] if first < 0 else ints


def matrix_equations(terms, n=16):
    """Rows of the linear system sum_k (L_k X R_k)_{ij} = 0 (all i, j) for the unknown n x n
    matrix X (unknown index i*n + j).  ``terms`` = list of (coefficient, L, R); L or R None
    means the identity."""
    rows = []
    for i in range(n):
        for j in range(n):
            row = {}
            for coeff, left, right in terms:
                lrow = [(p, left[i][p]) for p in range(n) if left[i][p] != 0] if left is not None else [(i, 1)]
                rcol = [(q, right[q][j]) for q in range(n) if right[q][j] != 0] if right is not None else [(j, 1)]
                for p, lv in lrow:
                    for q, rv in rcol:
                        key = p * n + q
                        row[key] = row.get(key, 0) + Fraction(coeff) * Fraction(int(lv)) * Fraction(int(rv))
            rows.append(row)
    return rows


def vec_to_matrix(vec, n=16):
    return [[vec[i * n + j] for j in range(n)] for i in range(n)]


def matrix_to_vec(mat, n=16):
    return [Fraction(mat[i][j]) if isinstance(mat[i][j], Fraction) else Fraction(int(mat[i][j]))
            for i in range(n) for j in range(n)]


def proportional(vec, target):
    """True if vec = c * target for some nonzero rational c (target nonzero)."""
    c = None
    for v, t in zip(vec, target):
        v = Fraction(v)
        t = Fraction(t)
        if t == 0:
            if v != 0:
                return False
            continue
        r = v / t
        if c is None:
            c = r
        elif r != c:
            return False
    return c is not None and c != 0


def span_equal(basis, expected, ncols):
    """span(basis) == span(expected) over QQ."""
    rb = exact_rank(basis, ncols)
    rexp = exact_rank(expected, ncols)
    rj = exact_rank(list(basis) + list(expected), ncols)
    return rb == rexp == rj


